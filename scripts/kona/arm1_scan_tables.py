#!/usr/bin/env python3
"""Write ucode/arm1_scan_tables.md: one row per boundary-scan chip-type
description, element list and chain record in the ARM firmware (arm1.u,
IRIX 6.5.30m).

Usage: arm1_scan_tables.py [ARM1_U] [SYMBOLS] [OUT]
       defaults: ucode/KONA/arm1.u ucode/arm1_symbols.tsv ucode/arm1_scan_tables.md

Read from the image through the AIF layout in scripts/arm1_disasm.py:

  - chip types: every symbol named *_chip_type, twenty words: chip code,
    a flag word, the instruction-register width, a pointer to the
    instruction-code list (or 0), and sixteen data-register lengths, one
    per instruction number 0-15;
  - chain records: every symbol named KONA_*_chain or HILO_*_chain, five words: chip count,
    total instruction-register bits, two run-time words (0xffffffff in the
    image) and a pointer to the element list;
  - element lists: the lists the chain records point at, sixteen bytes
    per chip: instance number, chip-type pointer and two run-time words.

The script checks that each element points at a chip type, that the
run-time words hold 0xffffffff, and that a chain's instruction-bit total
equals the sum of its chips' widths, and stops otherwise.
"""
import bisect
import struct
import sys

ARM1 = sys.argv[1] if len(sys.argv) > 1 else 'ucode/KONA/arm1.u'
SYMS = sys.argv[2] if len(sys.argv) > 2 else 'ucode/arm1_symbols.tsv'
OUT = sys.argv[3] if len(sys.argv) > 3 else 'ucode/arm1_scan_tables.md'

d = open(ARM1, 'rb').read()
h = struct.unpack('>32I', d[:128])
RO, RW, BASE, DBASE = h[5], h[6], h[10], h[13]


def off(a):
    if BASE <= a < BASE + RO:
        return 0x80 + a - BASE
    if DBASE <= a < DBASE + RW:
        return 0x80 + RO + a - DBASE
    raise SystemExit('address 0x%08x is outside the image' % a)


def words(a, n):
    o = off(a)
    return list(struct.unpack('>%dI' % n, d[o:o + 4 * n]))


def src(a):
    return '`arm1.u` RW +0x%x' % (a - DBASE)


syms, names, ordered = {}, {}, []
for line in open(SYMS):
    if line.startswith('#') or line.startswith('address'):
        continue
    a, _, n = line.rstrip('\n').split('\t')
    syms[n] = int(a, 16)
    names.setdefault(int(a, 16), n)
    ordered.append((int(a, 16), n))
ordered.sort()
starts = [a for a, _ in ordered]


def owner(a):
    i = bisect.bisect_right(starts, a) - 1
    return ordered[i]


refs = {}
for base, start, size in ((BASE, 0x80, RO), (DBASE, 0x80 + RO, RW)):
    for i in range(0, size, 4):
        v = struct.unpack('>I', d[start + i:start + i + 4])[0]
        refs.setdefault(v, []).append(base + i)


def holders(a):
    out = []
    for r in refs.get(a, []):
        oa, on = owner(r)
        out.append((on, (r - oa) // 4))
    return out


types = {}
for a, n in ordered:
    if n.endswith('_chip_type'):
        w = words(a, 20)
        if w[19] != 1 or (w[3] != 0) != (w[1] == 1):
            raise SystemExit('%s: bypass length or code-list flag breaks the layout' % n)
        types[a] = (n, w)

chains, lists = [], {}
for a, n in ordered:
    if not (n.startswith('KONA_') or n.startswith('HILO_')) or not n.endswith('_chain'):
        continue
    count, irbits, r0, r1, lp = words(a, 5)
    if (r0, r1) != (0xffffffff, 0xffffffff) or lp not in names:
        raise SystemExit('%s is not a chain record' % n)
    elems = []
    for k in range(count):
        inst, tp, e0, e1 = words(lp + 16 * k, 4)
        if tp not in types or (e0, e1) != (0xffffffff, 0xffffffff):
            raise SystemExit('%s element %d is not a chip entry' % (names[lp], k))
        elems.append((inst, tp))
    total = sum(types[tp][1][2] for _, tp in elems)
    if total != irbits:
        raise SystemExit('%s: %d instruction bits, chips sum to %d' % (n, irbits, total))
    chains.append((n, a, count, irbits, lp, holders(a)))
    lists[lp] = (n, elems)

used_in = {}
for lp, (cn, elems) in lists.items():
    for _, tp in elems:
        used_in.setdefault(tp, set()).add(names[lp])

L = []
L.append('# Boundary-scan chip types, element lists and chain records')
L.append('')
L.append('Generated by `scripts/arm1_scan_tables.py` from `ucode/KONA/arm1.u` (IRIX 6.5.30m) and '
         '[arm1_symbols.tsv](arm1_symbols.tsv); do not edit by hand. Every value is read from the image, and the '
         'script stops if a record breaks the shape below. The routines that walk these records (`jt_select_chip`, '
         '`chip_id`, the board probes) are in '
         '[arm1_functions.md](arm1_functions.md#boundary-scan-boards-and-serial-numbers).')
L.append('')
L.append('## Chip types')
L.append('')
L.append('**Established** (every record below). A chip-type description is twenty words: the chip code, a '
         'flag word (1 for the chips that use the shared instruction-code list `kona_jtag_ivalues`, 0 for the '
         'two that do not), the instruction-register width in bits, the pointer to that code list (0 when there '
         'is none) and sixteen data-register lengths in bits, one per instruction number 0-15. `jt_select_chip` '
         'puts the code for the chosen instruction number into the addressed chip\'s instruction register and '
         'adds that number\'s length to the running data-vector offset; every other chip gets the bypass code '
         '0xff, number 15, whose length is 1 in every record. `chip_id` reads with instruction number 5, '
         'which selects a 32-bit register in every chip that has a code list. The table gives the lengths of '
         'numbers 0, 2 (the number the configuration writers use), 5 and 12, the longest, and the element lists '
         'that place the chip; the full sixteen are listed [below](#data-register-lengths). The board each chip '
         'sits on follows from the lists. **Inferred** from the symbol prefixes and the board each list '
         'describes: on the raster boards `tg` is the texture generator, `tm` the texture memory, `tf` the '
         'texture filter, `imp` the image processor and `pg` the pixel generator; on the display board `fm2` is '
         'the bridge chip, `xmap8` the XMAP, `voc1` the VOC video chip, `adv7160` a video DAC and `tmc22090` '
         'a video encoder; on the geometry board `hip` is the host interface, `bef` the back-end chip and `ged` '
         'the distributor. A suffix letter (`imp8d`, `tf1c`, `pg2b`, `tm1c`, `ged1b`, `hip1b`) marks a later '
         'revision of the same chip, which keeps its chip code except where the table shows a new one.')
L.append('')
L.append('| Chip type | Address | Source | Kind | Chip code | Instruction bits | Code list | Number 0 | Number 2 | '
         'Number 5 | Number 12 | Longest | Placed in | Label |')
L.append('|---|---|---|---|---|---|---|---|---|---|---|---|---|---|')
for a in sorted(types):
    n, w = types[a]
    lens = w[4:20]
    place = sorted(used_in.get(a, ()))
    ptxt = ('%d lists' % len(place)) if len(place) > 1 else ('`%s`' % place[0] if place else 'no list')
    kind = 'scan chip with code list' if w[3] else 'scan part, no code list'
    L.append('| `%s` | 0x%08x | %s | %s | 0x%x | %d bits | %s | %d bits | %d bits | %d bits | %d bits | %d bits | '
             '%s | **Established** |'
             % (n, a, src(a), kind, w[0], w[2], ('`%s`' % names[w[3]]) if w[3] else 'none', lens[0], lens[2],
                lens[5], lens[12], max(lens), ptxt))
L.append('')
L.append('## Element lists')
L.append('')
L.append('**Established** (every list below). An element list holds one sixteen-byte entry per chip on a scan '
         'chain, in chain order: the chip\'s instance number among chips of its type, a pointer to its chip-type '
         'description and two words that `jt_select_chip` rewrites at run time (the selected instruction number '
         'and the chip\'s bit offset), 0xffffffff in the image. The chip count comes from the chain record that '
         'points at the list. The order of each list is [below](#chain-order).')
L.append('')
L.append('| List | Address | Source | Kind | Chips | Chip types | Instruction bits | Most common type | Chain record '
         '| Label |')
L.append('|---|---|---|---|---|---|---|---|---|---|')
for lp in sorted(lists):
    cn, elems = lists[lp]
    cnt = {}
    for _, tp in elems:
        cnt[tp] = cnt.get(tp, 0) + 1
    top = max(cnt, key=lambda t: cnt[t])
    L.append('| `%s` | 0x%08x | %s | chips in scan chain order | %d chips | %d types | %d bits | %d of `%s` | `%s` | '
             '**Established** |'
             % (names[lp], lp, src(lp), len(elems), len(cnt), sum(types[tp][1][2] for _, tp in elems), cnt[top],
                types[top][0], cn))
L.append('')
L.append('## Chain records')
L.append('')
L.append('**Established** (every record below). A chain record is five words: the chip count, the total '
         'instruction-register bits of its chips (the script checks the sum), two words `jt_select_chip` fills '
         'at run time (the data-register bits of the current selection and the selected chip index, 0xffffffff '
         'in the image) and the pointer to the element list. The last columns give the first word in the image '
         'that holds the record\'s address, as a symbol and a word offset from it, and how many words hold it; '
         'the chain maps hold one pointer per scan-chain slot.')
L.append('')
L.append('| Chain | Address | Source | Kind | Chips | Instruction bits | List | First holder | Word | Holders | Label |')
L.append('|---|---|---|---|---|---|---|---|---|---|---|')
for n, a, count, irbits, lp, hl in chains:
    first = ('`%s`' % hl[0][0], 'word %d' % hl[0][1]) if hl else ('none', 'none')
    L.append('| `%s` | 0x%08x | %s | five-word scan chain record | %d chips | %d bits | `%s` | %s | %s | %d | '
             '**Established** |' % (n, a, src(a), count, irbits, names[lp], first[0], first[1], len(hl)))
L.append('')
L.append('## Data-register lengths')
L.append('')
L.append('Each chip type\'s sixteen lengths in bits, for instruction numbers 0 to 15.')
L.append('')
L.append('```')
for a in sorted(types):
    n, w = types[a]
    L.append('%-20s %s' % (n, ' '.join(str(x) for x in w[4:20])))
L.append('```')
L.append('')
L.append('## Chain order')
L.append('')
L.append('Each element list in chain order, as chip type and instance number; a run of one type is written once '
         'with its count.')
L.append('')
L.append('```')
for lp in sorted(lists):
    cn, elems = lists[lp]
    runs = []
    for inst, tp in elems:
        t = types[tp][0].replace('_chip_type', '')
        if runs and runs[-1][0] == t:
            runs[-1][1].append(inst)
        else:
            runs.append((t, [inst]))
    L.append(names[lp])
    for t, insts in runs:
        L.append('    %s x%d (instances %s)' % (t, len(insts), ' '.join(str(i) for i in insts)))
L.append('```')
L.append('')
open(OUT, 'w').write('\n'.join(L))
print('chip types %d, lists %d, chains %d' % (len(types), len(lists), len(chains)))
