#!/usr/bin/env python3
"""Write ucode/arm1_param_handlers.md: one row per ARM handler whose body is
a fixed sequence that differs between handlers only in its constants
(arm1.u, IRIX 6.5.30m).

Usage: arm1_param_tables.py [DISASM] [HANDLERS] [OUT]
       defaults: ucode/arm1.s ucode/arm1_handlers.tsv ucode/arm1_param_handlers.md

Two families, each read from the disassembly function by function:

  - token stubs: functions whose whole body is one branch to the
    bad-command routine at 0x0c0017f4 (arm_badcmd) and that a token-map
    entry names; the token each one
    serves comes from arm1_handlers.tsv (the token map);
  - the light and user-clip-plane enable and disable handlers
    (e_light0-7, d_light0-7, e_clip_plane0-5, d_clip_plane0-5): the flag
    byte they write in the state block (r8), the value written, the words
    sent to ports r9 + 0x478 and r9 + 0x840, and the state word whose half
    is sent to r9 + 0x8c0 as the engine handler.

The script checks each body against the expected instruction shape and
stops if one differs, so a row is only written for code that was read.
"""
import re
import sys

DISASM = sys.argv[1] if len(sys.argv) > 1 else 'ucode/arm1.s'
HANDLERS = sys.argv[2] if len(sys.argv) > 2 else 'ucode/arm1_handlers.tsv'
OUT = sys.argv[3] if len(sys.argv) > 3 else 'ucode/arm1_param_handlers.md'
BADCMD = 0x0c0017f4

funcs, order, cur = {}, [], None
for line in open(DISASM):
    m = re.match(r'^([A-Za-z_$][\w$]*):\s*$', line)
    if m:
        cur = m.group(1)
        funcs[cur] = []
        order.append(cur)
        continue
    m = re.match(r'^([0-9a-f]{8}): ([0-9a-f]{8})  (.*)$', line)
    if m and cur:
        funcs[cur].append((int(m.group(1), 16), m.group(3).strip()))

tokens = {}
for line in open(HANDLERS):
    if line.startswith('#'):
        continue
    f = line.rstrip('\n').split('\t')
    if len(f) > 3:
        tokens[f[2]] = (f[0], f[1])


def imm(s):
    return int(s, 16) if s.startswith('0x') else int(s)


def stub_rows():
    rows = []
    for name in order:
        body = funcs[name]
        if len(body) != 1:
            continue
        m = re.fullmatch(r'b 0x([0-9a-f]+)(?: <.*>)?', body[0][1])
        if not m or int(m.group(1), 16) != BADCMD:
            continue
        if name not in tokens:
            continue  # no token-map entry reaches it; its prose row says so
        tok, tname = tokens[name]
        rows.append((name, body[0][0], tok, tname))
    return rows


def param_row(name):
    """Decode one enable or disable handler. Returns a dict or raises."""
    body = funcs[name]
    regs, out = {}, {}
    for addr, ins in body:
        m = re.fullmatch(r'mov r0, #(0x[0-9a-f]+|\d+)', ins)
        if m:
            regs['r0'] = imm(m.group(1))
            continue
        m = re.fullmatch(r'add r0, r0, #(0x[0-9a-f]+|\d+)', ins)
        if m:
            regs['r0'] += imm(m.group(1))
            continue
        if ins == 'mov r0, r8':
            regs['r0'] = 'r8'
            continue
        m = re.fullmatch(r'strb r0, \[r8, #(0x[0-9a-f]+)\]', ins)
        if m:
            out['flag'] = (imm(m.group(1)), regs['r0'])
            continue
        m = re.fullmatch(r'ldr r0, \[r8, #(0x[0-9a-f]+)\]', ins)
        if m:
            regs['r0'] = ('word', imm(m.group(1)), 'low')
            continue
        if ins == 'mov r0, r0, lsl #16':
            continue
        if ins == 'mov r0, r0, lsr #16':
            w = regs['r0']
            # lsl then lsr keeps the low half; a lone lsr keeps the high half
            prev = body[[a for a, _ in body].index(addr) - 1][1]
            regs['r0'] = (w[0], w[1], 'low' if prev == 'mov r0, r0, lsl #16' else 'high')
            continue
        m = re.fullmatch(r'str r0, \[r9, #(0x[0-9a-f]+)\]', ins)
        if m:
            out[imm(m.group(1))] = regs['r0']
            continue
        if ins == 'mov pc, lr':
            continue
        raise SystemExit('%s: unexpected instruction at %#x: %s' % (name, addr, ins))
    if 'flag' not in out or 0x478 not in out or 0x8c0 not in out:
        raise SystemExit('%s: missing a store' % name)
    out['addr'] = body[0][0]
    return out


def flagval(v):
    return 'r8' if v == 'r8' else str(v)


def handler(w):
    return '%s half of +0x%x' % (w[2], w[1])


lines = []
lines.append('# ARM handlers that differ only in their constants')
lines.append('')
lines.append('Generated by `scripts/arm1_param_tables.py` from [arm1.s](arm1.s) and '
             '[arm1_handlers.tsv](arm1_handlers.tsv); do not edit by hand. Each row is read from its '
             'own function in `arm1.u` (IRIX 6.5.30m), and the script stops if a body does not have '
             'the shape described here. Prose about each family is in '
             '[arm1_functions.md](arm1_functions.md).')
lines.append('')
lines.append('## Token stubs that branch to the bad-command routine')
lines.append('')
lines.append('**Established** (each body, and the token map). Each function below is one instruction, a '
             'branch to `arm_badcmd` (0x0c0017f4). That routine prints the current and previous token '
             'numbers from host-interface registers 0x200078 and 0x20007c, reads and prints 100 payload '
             'words and then reads the payload port forever, so a host that sends one of these tokens '
             'hangs the ARM. The token column is the token-map entry that names the function.')
lines.append('')
lines.append('| Handler | Address | Source | Token | Token name | Branch to | Kind | Effect | Label |')
lines.append('|---|---|---|---|---|---|---|---|---|')
for name, addr, tok, tname in stub_rows():
    lines.append('| `%s` | 0x%08x | `arm1.u` +0x%x | %s | %s | 0x%08x | unimplemented token stub | '
                 'prints payload, then hangs | **Established** |'
                 % (name, addr, addr - 0x0c000000, tok, '`%s`' % tname, BADCMD))
lines.append('')
lines.append('## Light and user-clip-plane enable and disable handlers')
lines.append('')
lines.append('**Established** (each body). `glEnable` and `glDisable` of `GL_LIGHTi` and '
             '`GL_CLIP_PLANEi` reach one of these leaf functions. Each writes a flag byte in the state '
             'block (r8), sends the light number or the plane enum (0x3000 + i) to port r9 + 0x478, for '
             'a light also sends the engine-memory address of that light\'s parameter block to port '
             'r9 + 0x840, and then sends half of a state word to port r9 + 0x8c0, the engine handler '
             'that applies the change. The light blocks are 0x23 words apart from 0x2c7. The disable '
             'handlers of the clip planes write the low byte of the state-block pointer r8 (shown as r8) as the flag '
             'instead of a constant 0. **Inferred:** that byte is 0. The reset and exception entries load '
             'r8 with 0 (`mov r8, #0x0` at 0x0c000000 and eight more), and the state-block offsets in '
             'every handler are taken from that base, so the flag is cleared as in the light handlers. '
             '**Established** (the engine routine started): the slot named by the half-word sent to port '
             'r9 + 0x8c0 is `mgeb_LiEnableLightS` for a light enable (low half of the word at r8 + 0x78, '
             'entry 51 of [geif_entries.md](geif_entries.md)), `mgeb_LiDisableLightS` for a light disable (high '
             'half of r8 + 0x74, entry 45), `mgeb_EnableUserClipPlane` for a plane enable (low half of r8 + 0x58, '
             'entry 19) and `mgeb_DisableUserClipPlane` for a plane disable (high half of r8 + 0x50, entry 9); '
             'the labels come from the shipped label table. **Inferred:** the Effect column and the Engine target '
             'column, from the instruction words of the four engine routines in [ge_compute.md](ge_compute.md). '
             'The plane routines store a flag pattern at the plane flag word (0x904 plus the enum less 0x3000) and '
             'go on to the clip-state rebuild; plane n is the number sent to port r9 + 0x478 and the Engine target '
             'of a plane is that flag word. The light routines never read the light number: they read only the '
             'second command word, the block address 0x2c7 + 0x23 n sent to port r9 + 0x840 (`mgeb_LiEnableLightS` '
             '0xdd3e, `mgeb_LiDisableLightS` 0xdcc0). Control word 0x87 is a count of enabled lights, not a bit '
             'set: each routine converts the constant register 0x1f (1.0) to the integer 1 and adds it to, or '
             'subtracts it from, the word (0xdd5e and 0xdd62; 0xdcc4 and 0xdcc8). The enable stores the new count '
             'in word 0 of the light\'s block (0xdd6c) and the disable stores 0 there (0xdd07). Both store only '
             'under a predicate on special register 0x2e, which receives block word 0 (0xdd52, 0xdcd5): the '
             'disable acts under code 0x7c and the enable under its inverse 0x7d, so an enable of a light already '
             'on, or a disable of one already off, leaves the count alone. The Engine target of a light is that '
             'block word.')
lines.append('')
lines.append('| Handler | Address | Source | Flag byte | Flag value | Port 0x478 | Port 0x840 | '
             'Engine handler from | Kind | Effect | Engine routine run | Engine target | Label |')
lines.append('|---|---|---|---|---|---|---|---|---|---|---|---|---|')
names = (['e_light%d' % i for i in range(8)] + ['d_light%d' % i for i in range(8)]
         + ['e_clip_plane%d' % i for i in range(6)] + ['d_clip_plane%d' % i for i in range(6)])
for name in names:
    r = param_row(name)
    light = 'light' in name
    on = name.startswith('e_')
    kind = ('light enable' if on else 'light disable') if light else \
        ('clip-plane enable' if on else 'clip-plane disable')
    num = int(name[-1])
    eng = ('mgeb_LiEnableLightS' if on else 'mgeb_LiDisableLightS') if light else \
        ('mgeb_EnableUserClipPlane' if on else 'mgeb_DisableUserClipPlane')
    if light:
        effect = '%s one %s the count in 0x87 (the light is named only by its block, 0x%x)' % ('adds' if on else 'subtracts', 'to' if on else 'from', 0x2c7 + 0x23 * num)
        target = 'block word 0x%x %s' % (0x2c7 + 0x23 * num, 'gets count' if on else 'gets zero')
    else:
        effect = 'plane %d flag %s, recount' % (num, 'set' if on else 'cleared')
        target = 'plane flag at word 0x%x' % (0x904 + num)
    runs = '`%s` for %s %d' % (eng, 'light' if light else 'plane', num)
    p840 = '0x%x' % r[0x840] if 0x840 in r else 'not written'
    lines.append('| `%s` | 0x%08x | `arm1.u` +0x%x | +0x%x | %s | 0x%x | %s | %s | %s | %s | %s | %s | **Inferred** |'
                 % (name, r['addr'], r['addr'] - 0x0c000000, r['flag'][0], flagval(r['flag'][1]),
                    r[0x478], p840, handler(r[0x8c0]), kind, effect, runs, target))
lines.append('')
open(OUT, 'w').write('\n'.join(lines))
