#!/usr/bin/env python3
"""Tests for docs-index: rows, titles, summaries, grouping, the keep marker, --check and ci-check.

Everything runs on a throwaway workspace built here.
"""
import os
import shutil
import subprocess
import sys
import tempfile
import unittest

HERE = os.path.dirname(os.path.abspath(__file__))
TOOL = os.path.join(HERE, "docs-index")
CI = os.path.join(HERE, "defs", "ci-check")


class DocsIndexTest(unittest.TestCase):
    def setUp(self):
        self.root = tempfile.mkdtemp()
        self.addCleanup(shutil.rmtree, self.root)

    def write(self, rel, text):
        full = os.path.join(self.root, rel)
        os.makedirs(os.path.dirname(full), exist_ok=True)
        with open(full, "w") as f:
            f.write(text)

    def read(self, rel):
        with open(os.path.join(self.root, rel)) as f:
            return f.read()

    def run_tool(self, *args, tool=TOOL):
        env = dict(os.environ, ORIGAMI_RE_WORKSPACE=self.root)
        return subprocess.run([sys.executable, tool, *args], cwd=self.root, env=env,
                              capture_output=True, text=True)

    def test_page_rows_and_summary(self):
        self.write("questions/open.md", "# Is the FIFO deep?\n\nUnknown. The manual says nothing about it.\nSecond line.\n")
        self.assertEqual(self.run_tool().returncode, 0)
        text = self.read("questions/README.md")
        self.assertEqual(text.split("\n")[0], "<!-- generated by tools/docs-index; do not edit, run it again -->")
        self.assertIn("| [open.md](open.md) | Is the FIFO deep? | Unknown. |", text)

    def test_summary_skips_tables_lists_and_quotes(self):
        self.write("platforms/a.md", "# A\n\n> note\n\n| x | y |\n|---|---|\n| 1 | 2 |\n\n- item\n\nThe board has [two links](http://x/y) and `code`. More.\n")
        self.run_tool()
        self.assertIn("| A | The board has two links and `code`. |", self.read("platforms/README.md"))

    def test_summary_is_trimmed(self):
        self.write("platforms/long.md", "# Long\n\n" + "word " * 60 + "end.\n")
        self.run_tool()
        line = [l for l in self.read("platforms/README.md").split("\n") if "long.md" in l][0]
        summary = line.split("|")[3].strip()
        self.assertTrue(summary.endswith("..."))
        self.assertLessEqual(len(summary), 120)

    def test_title_falls_back_to_file_name_and_pipes_are_escaped(self):
        self.write("platforms/plain.md", "no heading here\n")
        self.write("platforms/pipe.md", "# A | B\n\nBody.\n")
        self.run_tool()
        text = self.read("platforms/README.md")
        self.assertIn("| [plain.md](plain.md) | plain |", text)
        self.assertIn("A \\| B", text)

    def test_unit_subdirectory_is_one_row(self):
        self.write("devices/uart/registers.md", "# UART registers\n\nThe serial port.\n")
        self.write("devices/uart/notes.md", "# Notes\n\nExtra.\n")
        self.write("devices/gfx/README.md", "# Graphics\n\nA head.\n")
        self.run_tool()
        text = self.read("devices/README.md")
        self.assertIn("| [uart/](uart/registers.md) | UART registers | The serial port. |", text)
        self.assertIn("| [gfx/](gfx/README.md) | Graphics | A head. |", text)
        self.assertNotIn("notes.md", text)
        self.assertLess(text.index("gfx/"), text.index("uart/"))

    def test_component_subdirectory_is_a_group(self):
        self.write("software/kernel/boot.md", "# Boot\n\nHow it starts.\n")
        self.write("software/kernel/irq.md", "# IRQ\n\nInterrupts.\n")
        self.write("software/ucode/ge.md", "# GE\n\nMicrocode.\n")
        self.run_tool()
        text = self.read("software/README.md")
        self.assertIn("## kernel\n", text)
        self.assertIn("| [boot.md](kernel/boot.md) | Boot | How it starts. |", text)
        self.assertLess(text.index("## kernel"), text.index("## ucode"))

    def test_keep_marker_leaves_readme_alone(self):
        self.write("formats/README.md", "# Mine\n<!-- keep -->\n")
        self.write("formats/x.md", "# X\n\nA format.\n")
        self.assertEqual(self.run_tool().returncode, 0)
        self.assertEqual(self.read("formats/README.md"), "# Mine\n<!-- keep -->\n")
        self.assertEqual(self.run_tool("--check").returncode, 0)

    def test_unmarked_hand_written_readme_is_refused(self):
        self.write("formats/README.md", "# Mine\n")
        self.write("formats/x.md", "# X\n\nA format.\n")
        p = self.run_tool()
        self.assertEqual(p.returncode, 1)
        self.assertIn("hand-written", p.stderr)
        self.assertEqual(self.read("formats/README.md"), "# Mine\n")

    def test_check_reports_missing_and_stale_then_passes(self):
        self.write("evidence/a.md", "# A\n\nFirst.\n")
        p = self.run_tool("--check")
        self.assertEqual(p.returncode, 1)
        self.assertIn("missing", p.stderr)
        self.assertFalse(os.path.exists(os.path.join(self.root, "evidence/README.md")))
        self.run_tool()
        self.assertEqual(self.run_tool("--check").returncode, 0)
        self.write("evidence/a.md", "# A\n\nChanged.\n")
        p = self.run_tool("--check")
        self.assertEqual(p.returncode, 1)
        self.assertIn("stale", p.stderr)
        self.run_tool()
        self.assertEqual(self.run_tool("--check").returncode, 0)

    def test_second_run_changes_nothing_and_workspace_without_content_passes(self):
        self.assertEqual(self.run_tool("--check").returncode, 0)
        self.write("questions/q.md", "# Q\n\nWhy?\n")
        self.run_tool()
        first = self.read("questions/README.md")
        self.assertEqual(self.run_tool().stdout, "")
        self.assertEqual(self.read("questions/README.md"), first)

    def test_index_of_emptied_directory_is_removed(self):
        self.write("questions/q.md", "# Q\n\nWhy?\n")
        self.run_tool()
        os.remove(os.path.join(self.root, "questions/q.md"))
        self.assertEqual(self.run_tool("--check").returncode, 1)
        self.run_tool()
        self.assertFalse(os.path.exists(os.path.join(self.root, "questions/README.md")))

    def test_ci_check_fails_on_stale_index(self):
        self.write("questions/q.md", "# Q\n\nWhy?\n")
        p = self.run_tool(tool=CI)
        self.assertEqual(p.returncode, 1)
        self.assertIn("directory index is missing or stale", p.stderr)
        self.run_tool()
        self.assertEqual(self.run_tool(tool=CI).returncode, 0)


if __name__ == "__main__":
    unittest.main()
