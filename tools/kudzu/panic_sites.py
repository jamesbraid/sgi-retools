#!/usr/bin/env python3
"""Catalogue of the in-scope panic and assert call sites in the linked kernels.

Usage: retools/tools/kudzu/panic_sites.py extract [--rows FIRST:LAST] [--show] [--json OUT]
       retools/tools/kudzu/panic_sites.py render [--doc docs/panics.md]

Run from the repository root inside the toolchain environment (retools/tools/re-run python3 ...), with root/
populated and docs/inventory/panics.tsv generated by retools/tools/kudzu/os_tables.py.

extract lists every jal or bal to panic, cmn_err, assfail, nopanicdebugger or a printf-family console
printer (printf, sync_printf, dri_printf, icmn_err, icmn_err_tag, cmn_err_tag) in the kernels, and
attributes each call the way retools/tools/kudzu/os_tables.py does (the nearest objdump label before it). It keeps
the calls that the panics table lists as in scope, and checks that the count per row matches the table's
`sites` column. For each call it records the delay slot, the three nearest conditional branches above it,
the 16 instructions before it, and the values of a0 to a3 at the call. A call inside its label's recorded
symbol size is named after that label. A call past the end of the symbol is unlabelled code, named
sub_<address> where the address is the first instruction past the symbol that is not a bare return.

Argument values come from a straight-line scan backward from the call: moves, lui and addiu, shifts,
or, and words read from gp-relative or fixed addresses in the file's own data. The scan stops at a
branch, or at a branch target that another path can reach (a join); the value is then reported as not
resolved, with the reason. A string at a resolved address is read from the file's data (NUL-terminated).
File-name arguments of assertion calls are not copied; they name source files.

render writes docs/panics.md from the extracted sites and scripts/panic-conditions.json, which holds
the hand-written condition for each call, keyed by build and call address. A site with no condition yet
is listed with its message and marked "not yet read".
"""
import argparse
import bisect
import collections
import json
import os
import re
import subprocess
import sys

os.environ['LC_ALL'] = os.environ['LANG'] = 'C'
# The workspace comes from the current directory (tools/_workspace.py), not from this file's path.
TOOLS = os.path.dirname(os.path.dirname(os.path.realpath(__file__)))
sys.path.insert(0, TOOLS)
from _layout import Layout  # noqa: E402
from _workspace import find_workspace  # noqa: E402
REPO = find_workspace()
LAYOUT = Layout(REPO)

PANIC_CALLEES = ('panic', 'cmn_err', 'assfail', 'nopanicdebugger',
                 'printf', 'sync_printf', 'dri_printf', 'icmn_err', 'icmn_err_tag', 'cmn_err_tag')
# The printf wrappers pass a fixed level in a1 to the console printer (`li a1,N` before the call);
# the same N in IP27, IP30 and IP35. icmn_err and cmn_err_tag take their level from the caller.
PRINTF_LEVEL = {'printf': 6, 'dri_printf': 6, 'sync_printf': 38}
CONDITIONS = os.path.join(REPO, LAYOUT.config('panic-conditions.json'))
BUILD_LABEL = {'6.5.30/unix.IP27': '6.5.30 IP27', '6.5.30/unix.IP30': '6.5.30 IP30',
               '6.5.30/unix.IP35': '6.5.30 IP35'}
TABLE = os.path.join(REPO, LAYOUT.inventory_dir, 'panics.tsv')
CACHE = os.path.join(REPO, '.cache', 'panic-sites')
HDR = re.compile(r'^([0-9a-f]{16}) <([^>]+)>:$')
INS = re.compile(r'^\s*([0-9a-f]{16}):\t(.*)$')
CALL = re.compile(r'\b(?:jal|bal)\s+([0-9a-f]+)\b')
COND_BRANCHES = re.compile(r'^(beq|bne|bnez|beqz|blez|bgtz|bltz|bgez|blt|bge|bgt|ble|b)[a-z]*$')


def table_rows():
    """Rows of panics.tsv in scope, in table order, with the table's site count."""
    rows = []
    with open(TABLE, encoding='utf-8') as f:
        next(f)
        for ln in f:
            p = ln.rstrip('\n').split('\t')
            if len(p) == 7 and p[5] == 'in':
                rows.append({'binary': p[0], 'function': p[1], 'address': p[2], 'callee': p[3],
                             'sites': int(p[4])})
    return rows


def facts(binary, address, size=None):
    """Fact sheet for one routine, cached under .cache/panic-sites. An unlabelled routine passes its size."""
    os.makedirs(CACHE, exist_ok=True)
    key = os.path.join(CACHE, '%s_%s_%s.json' % (binary.replace('/', '_'), address, size or 'sym'))
    if not os.path.exists(key):
        cmd = [sys.executable, os.path.join(TOOLS, 'facts.py'), os.path.join('root', binary), address,
               '--out', key]
        if size:
            cmd += ['--size', hex(size)]
        r = subprocess.run(cmd, cwd=REPO, capture_output=True, text=True)
        if r.returncode != 0:
            sys.exit('facts.py failed for %s %s:\n%s' % (binary, address, r.stderr[-2000:]))
    with open(key, encoding='utf-8') as f:
        return json.load(f)


def listing(binary):
    """Instructions of .text as (address, text), and the labels objdump prints, as (address, name), in order.

    Labels follow objdump's own rule: a call site belongs to the nearest label before it, which is how
    retools/tools/kudzu/os_tables.py counts the panics table. Symbol sizes come from nm, so a label whose symbol
    ends before a call can be told apart from the routine that holds the call."""
    out = subprocess.run(['mips64-linux-gnuabi64-objdump', '-d', '--no-show-raw-insn', '-j', '.text',
                          os.path.join(REPO, 'root', binary)], capture_output=True, text=True,
                         errors='replace').stdout
    insns, labels = [], []
    for ln in out.splitlines():
        m = HDR.match(ln)
        if m:
            labels.append((int(m.group(1), 16), m.group(2)))
            continue
        m = INS.match(ln)
        if m:
            insns.append((int(m.group(1), 16), m.group(2).strip()))
    sizes = {}
    nm = subprocess.run(['mips64-linux-gnuabi64-nm', '-S', '--defined-only', os.path.join(REPO, 'root', binary)],
                        capture_output=True, text=True).stdout
    for ln in nm.splitlines():
        p = ln.split()
        if len(p) == 4 and p[2] in 'Tt':
            sizes[int(p[0], 16)] = int(p[1], 16)
    targets = {}
    for ln in subprocess.run(['mips64-linux-gnuabi64-nm', os.path.join(REPO, 'root', binary)], capture_output=True,
                             text=True).stdout.splitlines():
        p = ln.split()
        if len(p) == 3 and p[1] in 'Tt' and p[2] in PANIC_CALLEES:
            targets[int(p[0], 16)] = p[2]
    return insns, labels, sizes, targets


def sections(binary):
    """Allocated, file-backed sections of an ELF file: (name, address, bytes)."""
    from elftools.elf.elffile import ELFFile
    out = []
    with open(os.path.join(REPO, 'root', binary), 'rb') as f:
        elf = ELFFile(f)
        for sec in elf.iter_sections():
            if sec['sh_flags'] & 0x2 and sec['sh_type'] != 'SHT_NOBITS' and sec['sh_size']:
                out.append((sec.name, sec['sh_addr'], sec.data()))
    return out


def read_string(secs, addr, limit=240):
    """The NUL-terminated string at a virtual address, or None when no file-backed section holds it."""
    for _name, base, data in secs:
        if base <= addr < base + len(data):
            raw = data[addr - base:addr - base + limit]
            end = raw.find(b'\0')
            if end < 0:
                return None
            return raw[:end].decode('latin-1')
    return None


def window_text(insns, site_index, before=12):
    lo = max(0, site_index - before)
    return [[a, t] for a, t in insns[lo:site_index + 2]]


CALLER_SAVED = {'v0', 'v1', 'a0', 'a1', 'a2', 'a3', 'a4', 'a5', 'a6', 'a7', 't0', 't1', 't2', 't3', 't4',
                't5', 't6', 't7', 't8', 't9', 'at', 'ra'}
NO_DEST = ('b', 'j', 'sb', 'sh', 'sw', 'sd', 'sc', 'scd', 'swl', 'swr', 'sdl', 'sdr', 'sync', 'syscall', 'break',
           'teq', 'tne', 'tge', 'tlt', 'cache', 'pref', 'nop', 'mt', 'eret', 'wait', 'tlb', 'ei', 'di')
M64 = (1 << 64) - 1


def operands(text):
    mn, _, rest = text.partition('\t') if '\t' in text else text.partition(' ')
    ops = [o.strip() for o in rest.split(',')] if rest.strip() else []
    return mn.strip(), ops


def imm(tok):
    try:
        return int(tok, 0)
    except (ValueError, TypeError):
        return None


def writes(text, reg):
    mn, ops = operands(text)
    if mn.startswith(NO_DEST) or mn in ('jr', 'jal', 'jalr', 'bal'):
        return False
    return bool(ops) and ops[0] == reg


def resolve(insns, p, reg, ctx, depth=0):
    """Value of register reg just before instruction p, from the straight-line code above it.

    Returns (value, how). value is an int (64-bit, unsigned) or None. how names the rule that gave the
    value ('move', 'li', 'lui', 'add', 'or', 'shift', 'pool' for a word read from a fixed address,
    'entry' for a value the caller passed, or the reason it is unknown). A join (a branch target above p
    that is reached before a writer of reg) gives None, because another path may set reg."""
    if depth > 16 or reg == 'zero':
        return (0 if reg == 'zero' else None), ('zero' if reg == 'zero' else 'depth')
    i = p - 1
    while i >= 0:
        addr, text = insns[i]
        if i == ctx.get('skip'):
            i -= 1
            continue
        mn, ops = operands(text)
        if writes(text, reg):
            return eval_writer(insns, i, mn, ops, reg, ctx, depth)
        if mn in ('jal', 'bal', 'jalr'):
            if reg in CALLER_SAVED:
                return None, 'call at 0x%x clobbers %s' % (addr, reg)
        elif mn in ('j', 'b', 'jr'):
            return None, 'unconditional jump at 0x%x' % addr
        if addr in ctx['targets']:
            return None, 'join at 0x%x' % addr
        i -= 1
    return None, 'entry'


def eval_writer(insns, i, mn, ops, reg, ctx, depth):
    addr = insns[i][0]
    if mn == 'move' or (mn in ('or', 'daddu', 'addu') and len(ops) == 3 and 'zero' in ops[1:]):
        src = ops[1] if mn == 'move' else (ops[2] if ops[1] == 'zero' else ops[1])
        if src == 'zero':
            return 0, 'move'
        v, _h = resolve(insns, i, src, ctx, depth + 1)
        return v, 'move'
    if mn == 'li' and len(ops) == 2:
        v = imm(ops[1])
        return (v & M64 if v is not None else None), 'li'
    if mn in ('addiu', 'daddiu') and len(ops) == 3:
        base, bh = resolve(insns, i, ops[1], ctx, depth + 1)
        d = imm(ops[2])
        if base is None or d is None:
            return None, 'add of unknown at 0x%x (%s)' % (addr, bh)
        return (base + d) & M64, 'add'
    if mn in ('dadd', 'daddu', 'add', 'addu') and len(ops) == 3 and 'zero' not in ops[1:]:
        x, xh = resolve(insns, i, ops[1], ctx, depth + 1)
        y, yh = resolve(insns, i, ops[2], ctx, depth + 1)
        if x is None or y is None:
            return None, 'sum of unknown at 0x%x (%s)' % (addr, xh if x is None else yh)
        return (x + y) & M64, 'sum'
    if mn == 'lui' and len(ops) == 2:
        v = imm(ops[1])
        if v is None:
            return None, 'lui operand'
        v = (v & 0xffff) << 16
        if v & 0x80000000:
            v -= 1 << 32
        return v & M64, 'lui'
    if mn == 'ori' and len(ops) == 3:
        base, _h = resolve(insns, i, ops[1], ctx, depth + 1)
        v = imm(ops[2])
        if base is None or v is None:
            return None, 'or of unknown'
        return base | v, 'or'
    if mn in ('dsll', 'dsll32') and len(ops) == 3:
        base, _h = resolve(insns, i, ops[1], ctx, depth + 1)
        n = imm(ops[2])
        if base is None or n is None:
            return None, 'shift of unknown at 0x%x' % addr
        n += 32 if mn == 'dsll32' else 0
        return (base << n) & M64, 'shift'
    if mn in ('ld', 'lw') and len(ops) == 2 and '(' in ops[1]:
        off_s, _, base_reg = ops[1].partition('(')
        base_reg = base_reg.rstrip(')')
        off = imm(off_s) or 0
        if base_reg == 'gp':
            where = (ctx['gp'] + off) if ctx.get('gp') is not None else None
        else:
            basev, _h = resolve(insns, i, base_reg, ctx, depth + 1)
            where = (basev + off) if basev is not None else None
        if where is None:
            return None, 'load through unknown base at 0x%x' % addr
        raw = read_bytes(ctx['secs'], where, 8 if mn == 'ld' else 4)
        if raw is None:
            return None, 'word at 0x%x not in a file-backed section' % where
        return int.from_bytes(raw, 'big'), 'pool'
    return None, 'unhandled %s at 0x%x' % (mn, addr)


def value_at_call(insns, idx, reg, ctx):
    """Value of reg as the callee receives it: the call's delay slot runs first."""
    if idx + 1 < len(insns) and writes(insns[idx + 1][1], reg):
        mn, ops = operands(insns[idx + 1][1])
        return eval_writer(insns, idx + 1, mn, ops, reg, dict(ctx, skip=idx), 0)
    return resolve(insns, idx, reg, dict(ctx, skip=None))


def read_bytes(secs, addr, n):
    for _name, base, data in secs:
        if base <= addr and addr + n <= base + len(data):
            return data[addr - base:addr - base + n]
    return None


def is_return(text):
    return text in ('jr\tra', 'jr ra')


def unlabelled_start(insns, index_of, base):
    """First instruction at or after base that is not a bare return (jr ra and its delay slot)."""
    a = base
    while a in index_of and is_return(insns[index_of[a]][1]):
        a += 8
    return a


def branch_entries(insns):
    """Map each branch target to the addresses of the branches that jump to it."""
    entries = collections.defaultdict(list)
    for a, text in insns:
        mn, _ops = operands(text)
        if mn.startswith('b') or mn == 'j':
            m = re.search(r'\b([0-9a-f]{16})\b', text)
            if m:
                entries[int(m.group(1), 16)].append(a)
    return entries


def block_info(addr, target_sorted, bentries):
    """The nearest branch target at or below the site, and the branches that jump to it."""
    k = bisect.bisect_right(target_sorted, addr) - 1
    if k < 0:
        return {'start': None, 'entries': []}
    start = target_sorted[k]
    return {'start': '0x%x' % start, 'entries': ['0x%x' % e for e in bentries[start]]}


def extract(rows, show):
    out = []
    mismatches = []
    wanted = {(r['binary'], r['function'], r['callee']): r for r in rows}
    per_row = collections.Counter()
    for b in sorted({r['binary'] for r in rows}):
        insns, labels, sizes, targets = listing(b)
        label_addrs = [a for a, _n in labels]
        index_of = {a: i for i, (a, _t) in enumerate(insns)}
        secs = sections(b)
        btargets = set(branch_entries(insns))
        bentries = branch_entries(insns)
        target_sorted = sorted(btargets)
        for idx, (addr, text) in enumerate(insns):
            m = CALL.search(text)
            if not m:
                continue
            callee = targets.get(int(m.group(1), 16))
            if not callee:
                continue
            li = bisect.bisect_right(label_addrs, addr) - 1
            if li < 0:
                continue
            key = (b, labels[li][1], callee)
            if key not in wanted:
                continue
            per_row[key] += 1
            lab_addr, lab_name = labels[li]
            size = sizes.get(lab_addr, 0)
            fs = facts(b, hex(lab_addr))
            gp = int(fs['routine']['gp'], 16) if fs['routine'].get('gp') else None
            ctx = {'gp': gp, 'secs': secs, 'targets': btargets}
            if size and addr < lab_addr + size:
                name, rstart, rsize = lab_name, lab_addr, size
            else:
                rstart = unlabelled_start(insns, index_of, lab_addr + size)
                name, rsize = 'sub_0x%x' % rstart, None
            args = {}
            for reg in ('a0', 'a1', 'a2', 'a3'):
                v, how = value_at_call(insns, idx, reg, ctx)
                entry = {'value': ('0x%x' % v) if v is not None else None, 'how': how}
                if v is not None:
                    st = read_string(secs, v)
                    if st is not None:
                        entry['string'] = st
                args[reg] = entry
            guards = []
            for k in range(idx - 1, max(-1, idx - 400), -1):
                gmn, _gops = operands(insns[k][1])
                if COND_BRANCHES.match(gmn):
                    tm = re.search(r'\b([0-9a-f]{16})\b', insns[k][1])
                    guards.append({'address': '0x%x' % insns[k][0], 'text': insns[k][1],
                                   'target': ('0x' + tm.group(1)) if tm else None})
                    if len(guards) == 3:
                        break
            rec = {
                'binary': b,
                'table_function': lab_name,
                'function': name,
                'function_address': '0x%x' % rstart,
                'table_label_size': size,
                'callee': callee,
                'site': '0x%x' % addr,
                'delay_slot': insns[idx + 1][1] if idx + 1 < len(insns) else '',
                'args': args,
                'guards': guards,
                'window': window_text(insns, idx),
                'block': block_info(addr, target_sorted, bentries),
            }
            out.append(rec)
            if show:
                print('== %s %s %s @ %s (table: %s, label size %d)' % (
                    b, name, callee, rec['site'], lab_name, size))
                for a, t in rec['window']:
                    print('   %s  %s' % (a, t))
                for reg, e in args.items():
                    print('   %s=%s (%s) %s' % (reg, e['value'], e['how'],
                                               ('"%s"' % e['string']) if 'string' in e else ''))
                for g in guards:
                    print('   guard %s %s -> %s' % (g['address'], g['text'], g['target']))
                print('   block %s entered by %s' % (rec['block']['start'], rec['block']['entries']))
    for key, row in sorted(wanted.items()):
        if per_row[key] != row['sites']:
            mismatches.append('%s %s %s: table %d, found %d' % (key[0], key[1], key[2], row['sites'], per_row[key]))
    if mismatches:
        sys.exit('site counts disagree with the table:\n' + '\n'.join(mismatches))
    return out


def parse_rows(spec, rows):
    if not spec:
        return rows
    first, _, last = spec.partition(':')
    lo = int(first) if first else 0
    hi = int(last) if last else len(rows)
    return rows[lo:hi]


def load_conditions():
    if not os.path.exists(CONDITIONS):
        return {}
    with open(CONDITIONS, encoding='utf-8') as f:
        return json.load(f)


def cell(text):
    return text.replace('|', '\\|').replace('\n', ' ')


def unresolved(entry):
    return 'not resolved (%s)' % entry['how'] if entry['value'] is None else 'value %s' % entry['value']


def message(rec):
    """The message the call passes: the format or expression string, and the arguments that qualify it."""
    callee = rec['callee']
    args = rec['args']
    if callee == 'cmn_err':
        lvl = int(args['a0']['value'], 16) if args['a0']['value'] else None
        fmt = args['a1']
        text = fmt.get('string')
        head = ('`%s`' % text.replace('\n', '\\n').replace('\t', '\\t')) if text is not None else (
            'format %s' % unresolved(fmt))
        return 'level %s, %s' % (lvl if lvl is not None else 'not resolved', head)
    if callee == 'assfail':
        expr = args['a0']
        line = args['a2']['value']
        text = expr.get('string')
        head = '`%s`' % text if text is not None else 'expression %s' % unresolved(expr)
        return '%s, line %s (file argument not copied)' % (head, int(line, 16) if line else 'not resolved')
    if callee in PRINTF_LEVEL:
        return 'level %d (set by the printf wrapper), %s' % (PRINTF_LEVEL[callee], format_text(args['a0']))
    if callee == 'icmn_err':
        return 'level %s, %s' % (level_text(args['a0']), format_text(args['a1']))
    if callee in ('icmn_err_tag', 'cmn_err_tag'):
        return 'tag %s, level %s, %s' % (level_text(args['a0']), level_text(args['a1']), format_text(args['a2']))
    return format_text(args['a0'])


def level_text(entry):
    return str(int(entry['value'], 16)) if entry['value'] is not None else 'not resolved'


def format_text(fmt):
    text = fmt.get('string')
    if text is not None:
        return '`%s`' % text.replace('\n', '\\n').replace('\t', '\\t')
    return 'format %s' % unresolved(fmt)


def render(doc_path):
    rows = table_rows()
    conds = load_conditions()
    recs = extract(rows, show=False)
    by_binary = collections.OrderedDict()
    for rec in recs:
        by_binary.setdefault(rec['binary'], collections.OrderedDict()).setdefault(
            (rec['function'], rec['function_address']), []).append(rec)
    keys = {'%s|%s' % (r['binary'], r['site']) for r in recs}
    stale = sorted(k for k in conds if k not in keys)
    if stale:
        sys.exit('conditions with no matching site: %s' % ', '.join(stale))
    total = len(recs)
    written = sum(1 for r in recs if '%s|%s' % (r['binary'], r['site']) in conds)
    routines = len({(r['binary'], r['function_address']) for r in recs})
    lines = [
        '# Panic and assert sites',
        '',
        '<!-- Generated by retools/tools/kudzu/panic_sites.py render from docs/inventory/panics.tsv and '
        'scripts/panic-conditions.json. Edit the conditions file, not this page. -->',
        '',
        'Every call from a kernel routine to `panic`, `cmn_err`, `assfail`, `nopanicdebugger` or a printf-family '
        'console printer (`printf`, `sync_printf`, `dri_printf`, `icmn_err`, `icmn_err_tag`, `cmn_err_tag`) in the '
        'linked IRIX 6.5.30 kernels IP27, IP30 and IP35 that the panics table lists as in scope. The 6.5.22 '
        'release has no linked kernel yet, so it has no rows here.',
        '',
        'Each row gives the call address, the callee, the message the call passes, and the condition under '
        'which the call runs. The message is read from the binary: the register value at the call, followed '
        'to a string in the file-backed data. `cmn_err` takes its level in a0 and its format in a1; `panic` '
        'takes its format in a0; `assfail` takes the failed expression in a0, the file name in a1 (not '
        'copied, it names a source file) and the line number in a2. `icmn_err` takes the level in a0 and the '
        'format in a1; `icmn_err_tag` and `cmn_err_tag` take a tag in a0, the level in a1 and the format in a2. '
        '`printf`, `sync_printf` and `dri_printf` take the format in a0, and their wrapper passes a fixed level '
        'in a1 (6, 38 and 6), shown in the message.',
        '',
        'Grades: a message that is shown is established from the binary. `not resolved` means the scan could '
        'not follow the register: it is set on two paths that join before the call, or it comes from a '
        'pointer the routine loads at run time. A condition is established when the branch that decides the '
        'call was read in the disassembly; `not established` means no branch in the listing reaches the call.',
        '',
        'Counts: %d call sites in %d routines; %d have a written condition, %d do not yet.' % (
            total, routines, written, total - written),
        '',
    ]
    for binary, funcs in by_binary.items():
        lines += ['## %s kernel' % BUILD_LABEL.get(binary, binary), '']
        for (fname, faddr), sites in funcs.items():
            lines += ['### `%s`' % fname, '']
            tl = sites[0]['table_function']
            if fname.startswith('sub_'):
                size = sites[0]['table_label_size']
                lines.append('Unlabelled code at %s, after the recorded end of `%s` (%d bytes). The panics table '
                             'counts these calls under `%s`.' % (faddr, tl, size, tl))
            else:
                lines.append('Routine at %s.' % faddr)
            lines += ['', '| Call | Callee | Message | Condition |', '|---|---|---|---|']
            for rec in sites:
                key = '%s|%s' % (binary, rec['site'])
                cond = conds.get(key, 'not yet read')
                lines.append('| %s | %s | %s | %s |' % (
                    rec['site'], rec['callee'], cell(message(rec)), cell(cond)))
            lines.append('')
    text = '\n'.join(lines).rstrip('\n') + '\n'
    with open(os.path.join(REPO, doc_path), 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)
    print('wrote %s: %d sites, %d with conditions' % (doc_path, total, written))


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    sub = ap.add_subparsers(dest='cmd', required=True)
    ex = sub.add_parser('extract')
    ex.add_argument('--rows', help='table row range FIRST:LAST (0-based, in-scope rows)')
    ex.add_argument('--show', action='store_true', help='print each site with its window')
    ex.add_argument('--json', help='write the site records to this file')
    rd = sub.add_parser('render')
    rd.add_argument('--doc', default=LAYOUT.page('panics.md', 'kernel'))
    a = ap.parse_args()
    if a.cmd == 'render':
        render(a.doc)
        return
    rows = parse_rows(a.rows, table_rows())
    recs = extract(rows, a.show)
    if a.json:
        with open(a.json, 'w', encoding='utf-8') as f:
            json.dump(recs, f, indent=1, sort_keys=True)
    print('%d sites in %d routines' % (len(recs), len({(r['binary'], r['function_address']) for r in recs})))


if __name__ == '__main__':
    main()
