#!/usr/bin/env python3
"""Stage 5: write the human report from the stage 4 tables.

Usage: report.py CONFIG.json --dir work/ASIC --repo DATASHEET_REPO --out ASIC-census.md [--notes FILE]

The numbers and tables come from the files; --notes is hand-written text (findings,
recommendations) appended verbatim so a rerun refreshes the data without losing it.
"""
import argparse
import collections
import csv
import hashlib
import json
import os
import subprocess


def tsv(path):
    return list(csv.DictReader(open(path), delimiter='\t')) if os.path.exists(path) else []


def sha(path):
    h = hashlib.sha256()
    with open(path, 'rb') as f:
        for b in iter(lambda: f.read(1 << 20), b''):
            h.update(b)
    return h.hexdigest()[:16]


def table(head, rows):
    out = ['| ' + ' | '.join(head) + ' |', '|' + '|'.join('---' for _ in head) + '|']
    out += ['| ' + ' | '.join(str(c) for c in r) + ' |' for r in rows]
    return '\n'.join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('config')
    ap.add_argument('--dir', required=True)
    ap.add_argument('--repo', required=True)
    ap.add_argument('--out', required=True)
    ap.add_argument('--notes')
    a = ap.parse_args()
    cfg = json.load(open(a.config))
    asic = cfg['asic']
    d = a.dir
    census = tsv(os.path.join(d, asic + '-census.tsv'))
    sites = tsv(os.path.join(d, 'sites.tsv'))
    windows = tsv(os.path.join(d, asic + '-census-windows.tsv'))
    unres = tsv(os.path.join(d, 'unresolved.tsv'))
    sus = tsv(os.path.join(d, 'suspects.tsv'))
    scope = tsv(os.path.join(d, 'scope.tsv'))
    summ = json.load(open(os.path.join(d, asic + '-census.summary.json')))
    stats = json.load(open(os.path.join(d, 'scan-stats.json')))
    qrev = open(os.path.join('work', 'model', 'MODEL_REV')).read().strip() if os.path.exists('work/model/MODEL_REV') else '?'
    try:
        orev = subprocess.run(['git', '-C', a.repo, 'rev-parse', '--short=12', 'HEAD'], capture_output=True, text=True).stdout.strip()
    except Exception:
        orev = '?'

    bridge_like = asic in ('bridge', 'pic', 'tiocp')   # the fixed sentences below describe the Bridge family
    nospec = cfg.get('mode') == 'no-spec'              # no published specification: datasheet sections have nothing to compare
    not_compared = 'Not compared: this run has no published specification.'
    L = []
    L.append('# %s register-access census\n' % cfg.get('title', asic))
    L.append('Mode: **%s**. Generated by `retools/tools/chips/run.sh configs/%s.json`; the TSVs beside this file hold every row.\n' % (cfg.get('mode', '?'), asic))
    L.append('## Inputs\n')
    imgs = []
    for i in cfg['images']:
        p = os.path.join('root', i['path'].split('root/', 1)[-1]) if 'path' in i else ''
        imgs.append((i['label'], i.get('path', ''), sha(p) if p and os.path.exists(p) else '?', i.get('note', '')))
    L.append(table(['image', 'path', 'sha256 (16)', 'note'], imgs))
    L.append('\nDatasheet checkout `%s` (datasheets, spec transcriptions); model at `%s` (model source, read only).\n' % (orev, qrev[:12]))

    L.append('## Summary\n')
    L.append('- **%d access sites** resolved to a window offset, folded into **%d register rows** (one per variant and 8-byte slot). '
             'Sites are summed over the images; the two kernels carry the same accessor code, so most sites appear once per kernel.' % (len(sites), len(census)))
    by = collections.OrderedDict()
    for r in census:
        by.setdefault(r['variant'], []).append(r)
    rows = []
    for v, rs in by.items():
        qc = collections.Counter(r['model'] for r in rs)
        dc = collections.Counter(r['datasheet'] for r in rs)
        sc = collections.Counter(r['spec'] for r in rs)
        rows.append((v, len(rs), sum(int(r['sites']) for r in rs),
                     qc.get('handled-specified', 0), qc.get('handled-guessed', 0), qc.get('unhandled', 0) + qc.get('out-of-scope', 0),
                     dc.get('absent', 0) + dc.get('no-datasheet', 0), sc.get('absent', 0), sc.get('conflict-access', 0)))
    L.append('')
    L.append(table(['variant', 'rows', 'sites', 'model: handled+specified', 'model: handled, guessed or LOG_UNIMP',
                    'model: unhandled / out of scope', 'not in datasheet', 'not in spec', 'spec conflict'], rows))
    L.append('\n`?` is an access whose path names no chip variant (the identification-word read every driver does before it knows which chip it holds). '
             + ('`tiocp` has no emulator datasheet or model, so its rows are listed but not judged.' if bridge_like else
                'This census compares only with the published specification: no emulator datasheet or model is read, so the datasheet and model columns carry no information.'))
    L.append('\nSite basis: %s.' % ', '.join('%d %s' % (n, k) for k, n in collections.Counter(s['basis'] for s in sites).most_common()))
    L.append('\n### Scan coverage and what is unresolved\n')
    tot = {}
    for r in scope:
        tot.setdefault(r['image'], [0, 0])
        tot[r['image']][0] += 1
        tot[r['image']][1] += int(r['sites']) > 0
    L.append('- Accessor functions seeded (`seeds.args`): ' + '; '.join('%s %d, %d with at least one resolved access' % (k, v[0], v[1]) for k, v in tot.items()) + '.')
    # one call can pass a window pointer in several argument registers, so rows and calls differ
    calls = {(u['image'], u['function'], u['addr']) for u in unres}
    L.append('- Window pointers passed to a callee the config does not seed (**unresolved**, site in `%s/unresolved.tsv`): %d distinct calls (%d rows).' % (d, len(calls), len(unres)))
    for u in unres[:6]:
        L.append('  - %s `%s` @%s calls `%s` with the window pointer in %s' % (u['image'], u['function'], u['addr'][-6:], u['callee'], u['arg']))
    if bridge_like:
        L.append('- Loads and stores in the seeded scope whose base register the scan could not resolve and whose displacement falls where registers live (%s): %d, almost all `xbridge_attach` writing its own state record (**unresolved, inspected only by listing; `suspects.tsv`**).'
                 % ('0x100..0x2ff', len(sus)))
    else:
        L.append('- Loads and stores whose base register the scan could not resolve and whose displacement looks like a register offset (%d rows in `suspects.tsv`) are driver record fields and stack frames more often than registers: **unresolved, listed only**.' % len(sus))
    L.append('- Index registers are not followed: a family reached through an array index is recorded at its base with `idx=1` (device 0..7, interrupt 0..7, ATE). The family extent comes from the datasheet, not the code.')
    L.append('- Returned pointers: a function that hands back a pointer into the window is recorded as a kind-`a` site at the pointer offset (this is how the one-wire register and the configuration windows are reached).')
    L.append('- Basic blocks never reached by the flow analysis (jump tables) in the seeded scope: %s.' % ', '.join('%s %s' % (k.split(':')[0], v) for k, v in stats.items() if k.endswith('orphan_blocks')))

    def rank(variant):
        rs = [r for r in by.get(variant, []) if r['model'] in ('unhandled', 'handled-guessed')]
        return sorted(rs, key=lambda r: (-int(r['functions']), -int(r['sites'])))

    for v in (('bridge', 'xbridge', 'pic') if bridge_like else ()):
        rs = rank(v)
        L.append('\n## Top unmodelled or guessed registers: %s\n' % v)
        if not rs:
            L.append('None.')
            continue
        L.append(table(['rank', 'offset', 'name (datasheet/spec/model)', 'access', 'widths', 'functions', 'sites', 'model class', 'detail', 'datasheet', 'spec'],
                       [(n + 1, r['offset'] + ('+8n' if r['idx'] == '1' else ''), r['name'][:40], r['access_seen'], r['widths'], r['functions'], r['sites'],
                         r['model'], r['model_detail'][:60], r['datasheet'], r['spec']) for n, r in enumerate(rs[:15])]))
        if len(rs) > 15:
            L.append('\n%d more in the TSV.' % (len(rs) - 15))

    L.append('\n## Touched by IRIX but absent from the datasheet\n')
    miss = [r for r in census if r['datasheet'] == 'absent']
    if nospec:
        L.append(not_compared)
    elif miss:
        L.append(table(['variant', 'offset', 'access', 'widths', 'functions', 'sites', 'spec', 'example'],
                       [(r['variant'], r['offset'], r['access_seen'], r['widths'], r['functions'], r['sites'], r['spec'], r['example']) for r in miss]))
    else:
        L.append('None for bridge or xbridge; the datasheets list every slot the kernels touch. For pic, see below.' if bridge_like else 'None.')

    L.append('\n## Datasheet and spec disagreements (on registers IRIX touches)\n')
    dis = [r for r in census if r['spec'] in ('conflict-access',) or (r['spec'] == 'absent' and r['datasheet'] == 'listed')]
    if nospec:
        L.append(not_compared)
    elif dis:
        L.append(table(['variant', 'offset', 'name', 'datasheet', 'spec', 'tasks'], [(r['variant'], r['offset'], r['name'][:40], r['datasheet_ref'], r['spec'], r['tasks']) for r in dis]))
    else:
        L.append('None found among touched registers.')

    L.append('\n## Listed in the datasheet or spec, never touched by the scanned objects\n')
    for v, un in summ['unreached'].items():
        if nospec:
            L.append('- **%s**: %s' % (v, not_compared))
        elif un:
            L.append('- **%s**: %s' % (v, '; '.join('%s %s (%s)' % (u['offset'], u['name'][:30], ', '.join(u['listed_in'])) for u in un)))
        else:
            L.append('- **%s**: none (index families count as reached when their base is touched; assumed extent 0x40)' % v)

    if bridge_like or summ.get('window_rows', 0):
        L.append('\n## Hand-off: accesses through the Bridge into PCI device windows and configuration space\n')
        L.append('These are not Bridge registers; they are the register traffic of the chips behind it. `%s-census-windows.tsv` carries %d rows (%d sites). '
                 'Feed them to the IOC3, IOC4, SCSI and PCI-configuration censuses as their access list.' % (asic, summ.get('window_rows', 0), summ.get('window_sites', 0)))
    agg = collections.defaultdict(lambda: [0, 0])
    for w in windows:
        agg[w['window']][0] += 1
        agg[w['window']][1] += int(w['sites'])
    if agg:
        L.append('')
        L.append(table(['window', 'distinct (offset, rw, width)', 'sites'], [(k, v[0], v[1]) for k, v in agg.items()]))

    if a.notes and os.path.exists(a.notes):
        L.append('\n' + open(a.notes).read())
    open(a.out, 'w').write('\n'.join(L) + '\n')
    print('wrote', a.out)


if __name__ == '__main__':
    main()
