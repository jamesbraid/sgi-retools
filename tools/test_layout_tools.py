class SetupCloneTests(Workspace):
    """setup-clone.sh finds the sibling pins on either layout."""

    def test_siblings_are_cloned_from_the_pins(self):
        base = tempfile.mkdtemp()
        self.addCleanup(shutil.rmtree, base)
        sib = os.path.join(base, "other.git")
        os.makedirs(sib)
        git = lambda cwd, *a: subprocess.run(("git", "-c", "user.name=t", "-c", "user.email=t@example.invalid",
                                              "-c", "commit.gpgsign=false", "-C", cwd) + a, check=True, capture_output=True, text=True)
        git(sib, "init", "-q")
        git(sib, "commit", "-q", "--allow-empty", "-m", "x")
        sha = git(sib, "rev-parse", "HEAD").stdout.strip()
        self.write(self.LAYOUT["config"] + "/inventory-siblings.json", json.dumps({"other": sha}))
        os.makedirs(os.path.join(self.ws, "tools"), exist_ok=True)
        shutil.copy(os.path.join(HERE, "setup-clone.sh"), os.path.join(self.ws, "tools", "setup-clone.sh"))
        git(self.ws, "init", "-q")
        shutil.rmtree(os.path.join(self.ws, "root"))
        env = dict(os.environ, SIBLING_BASE=base)
        r = subprocess.run(["sh", "tools/setup-clone.sh"], cwd=self.ws, capture_output=True, text=True, env=env)
        self.assertEqual(r.returncode, 0, r.stderr)
        self.assertIn("sibling other at %s" % sha[:12], r.stdout)
        self.assertTrue(os.path.isdir(os.path.join(self.ws, ".cache", "siblings", "other", ".git")))
        self.assertIn("evidence/irix-files.md", r.stdout)


class OldSetupCloneTests(SetupCloneTests):
    LAYOUT = OLD


if __name__ == "__main__":
    unittest.main()
