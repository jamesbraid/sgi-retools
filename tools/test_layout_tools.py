#!/usr/bin/env python3
"""The tools that read a workspace find their inputs by subject: tools/config/, generated/, COVERAGE.md and the
<subject>/readings/ pages.

Each test builds a throwaway workspace and runs the tool on it."""
import json
import os
import shutil
import subprocess
import sys
import tempfile
import unittest

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import firmware_layout  # noqa: E402
import grade_readings  # noqa: E402

CONFIG = {"family": "x", "siblings": {},
          "docs": {"prose": ["references/*.md", "software/*/readings/*.md"], "headers": [], "tables": [], "index": [],
                   "dumps": [], "skip": ["generated/inventory/*"]},
          "prepare": [], "binaries": [], "review_required": ["software/kernel/readings/t*.md"]}

LAYOUT = dict(config="tools/config", inventory="generated/inventory", coverage="COVERAGE.md",
              readings="software/kernel/readings")


class Workspace(unittest.TestCase):
    LAYOUT = LAYOUT

    def setUp(self):
        self.ws = tempfile.mkdtemp()
        self.addCleanup(shutil.rmtree, self.ws)
        L = self.LAYOUT
        self.write(L["config"] + "/inventory-config.json", json.dumps(CONFIG))
        self.write(L["config"] + "/inventory-root.sha256", "")
        self.write(L["config"] + "/inventory-siblings.json", "{}")
        self.write(L["coverage"], "# Coverage\n\n<!-- inventory:begin -->\nold\n<!-- inventory:end -->\n")
        os.makedirs(os.path.join(self.ws, "root"))

    def write(self, rel, text):
        path = os.path.join(self.ws, rel)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8") as f:
            f.write(text)

    def read(self, rel):
        with open(os.path.join(self.ws, rel), encoding="utf-8") as f:
            return f.read()

    def run_tool(self, script, *args, **kw):
        env = dict(os.environ)
        env.pop("RETOOLS_WORKSPACE", None)
        return subprocess.run([sys.executable, os.path.join(HERE, script), *args], cwd=self.ws,
                              capture_output=True, text=True, env=env, **kw)


class InventoryTests(Workspace):
    def test_coverage_links_the_audits_table_once(self):
        self.write(self.LAYOUT["inventory"] + "/audits.tsv",
                   "table\tdate\tsample\treal\tshallow\twrong\nfunctions\t2026-01-01\t10\t9\t1\t0\n")
        r = self.run_tool("inventory.py", "--repo", self.ws)
        self.assertEqual(r.returncode, 0, r.stderr)
        cov = self.read(self.LAYOUT["coverage"])
        self.assertIn("### Audited", cov)
        self.assertIn("[generated/inventory/audits.tsv](generated/inventory/audits.tsv)", cov)
        self.assertNotIn("audits.tsv/audits.tsv", cov)

    def test_tables_and_coverage_land_where_the_workspace_keeps_them(self):
        r = self.run_tool("inventory.py", "--repo", self.ws)
        self.assertEqual(r.returncode, 0, r.stderr)
        L = self.LAYOUT
        self.assertTrue(os.path.isfile(os.path.join(self.ws, L["inventory"], "functions.tsv")))
        cov = self.read(L["coverage"])
        self.assertIn("Generated by `retools/tools/inventory.py`", cov)
        self.assertIn("[%s/](%s/README.md)" % (L["inventory"], L["inventory"]), cov)
        self.assertIn("(%s/functions.tsv)" % L["inventory"], cov)

    def test_a_missing_root_manifest_is_named_by_its_path(self):
        os.remove(os.path.join(self.ws, self.LAYOUT["config"], "inventory-root.sha256"))
        r = self.run_tool("inventory.py", "--repo", self.ws)
        self.assertNotEqual(r.returncode, 0)
        self.assertIn("%s/inventory-root.sha256 is missing" % self.LAYOUT["config"], r.stderr)

    def test_update_pins_writes_the_pin_file_in_place(self):
        r = self.run_tool("inventory.py", "--repo", self.ws, "--update-pins")
        self.assertEqual(r.returncode, 0, r.stderr)
        self.assertEqual(json.loads(self.read(self.LAYOUT["config"] + "/inventory-siblings.json")), {})


class SiblingConfigTests(Workspace):
    """A sibling is read at its pinned commit, which may predate the move to tools/config/."""

    def make_sibling(self, config):
        sib = tempfile.mkdtemp()
        self.addCleanup(shutil.rmtree, sib)
        git = lambda *a: subprocess.run(("git", "-c", "user.name=t", "-c", "user.email=t@example.invalid",
                                         "-c", "commit.gpgsign=false", "-C", sib) + a, check=True, capture_output=True, text=True)
        git("init", "-q")
        cfg = dict(CONFIG, family="other")
        os.makedirs(os.path.join(sib, config))
        with open(os.path.join(sib, config, "inventory-config.json"), "w") as f:
            json.dump(cfg, f)
        os.makedirs(os.path.join(sib, LAYOUT["readings"]))
        for name, text in (("notes.md", "# notes\n"), ("x.h", "/* x */\n"), ("x.tsv", "a\tb\n")):   # git archive wants a match per glob
            with open(os.path.join(sib, LAYOUT["readings"], name), "w") as f:
                f.write(text)
        git("add", ".")
        git("commit", "-q", "-m", "x")
        return sib, git("rev-parse", "HEAD").stdout.strip()

    def test_sibling_pinned_before_the_move_is_read(self):
        for sib_config in ("tools/config", "scripts"):
            sib, sha = self.make_sibling(sib_config)
            cfg = json.loads(self.read(self.LAYOUT["config"] + "/inventory-config.json"))
            cfg["siblings"] = {"other": sib}
            self.write(self.LAYOUT["config"] + "/inventory-config.json", json.dumps(cfg))
            self.write(self.LAYOUT["config"] + "/inventory-siblings.json", json.dumps({"other": sha}))
            r = self.run_tool("inventory.py", "--repo", self.ws)
            self.assertEqual(r.returncode, 0, "%s: %s" % (sib_config, r.stderr))
            self.assertNotIn("has no", r.stderr)
            self.assertIn("compared 0 entries", self.read(self.LAYOUT["coverage"]))


class ComponentToolTests(Workspace):
    """The per-repository tools find a component's files under software/ and devices/, or at the top of an
    old workspace, with no path on the command line."""
    KERNEL = "software/kernel"
    HEADER = "devices/ge/GE.h"

    def test_kernel_commands_reads_the_default_paths(self):
        self.write(self.HEADER, "KONA_HP_CLEAR = 0x161,\n")
        self.write(self.KERNEL + "/disasm/m/m.text.s",
                   "glabel f\n ld $a0,2304($s0)\n li $a1,0x161\n jal gfx_pio_write_32\n nop\n")
        r = self.run_tool("kona/kernel_commands.py")
        self.assertEqual(r.returncode, 0, r.stderr)
        self.assertIn("m\tf\t0x161\tKONA_HP_CLEAR\t1", r.stdout)

    def test_coverage_page_and_scripts_are_not_needed(self):
        # a workspace with the component directory but no other file of either layout
        self.write(self.HEADER, "")
        self.write(self.KERNEL + "/disasm/m/m.text.s", "")
        r = self.run_tool("kona/kernel_commands.py")
        self.assertEqual(r.returncode, 0, r.stderr)


class ReadingToolTests(Workspace):
    def test_firmware_config_is_read_from_the_config_directory(self):
        cfg = firmware_layout.read_config(self.ws)
        self.assertEqual(cfg["family"], "x")
        self.assertEqual(firmware_layout.read_config(tempfile.gettempdir() + "/nothing-here-xyz"), {})

    def test_routines_pages_are_the_ones_the_config_lists_for_review(self):
        page = os.path.join(self.ws, self.LAYOUT["readings"], "t1.md")
        self.write(self.LAYOUT["readings"] + "/t1.md", "# t1\n")
        self.assertTrue(grade_readings.is_routines_file(page, self.ws))
        self.assertTrue(grade_readings.needs_review(page, self.ws))
        other = os.path.join(self.ws, self.LAYOUT["readings"], "plain.md")
        self.write(self.LAYOUT["readings"] + "/plain.md", "# p\n")
        self.assertFalse(grade_readings.is_routines_file(other, self.ws))

    def test_check_doc_takes_the_functions_table_of_the_layout(self):
        self.write(self.LAYOUT["inventory"] + "/functions.tsv",
                   "binary\trole\tabi\telf_section\taddress\tsize\tname\tsource\tcode_sha\n")
        self.write(self.LAYOUT["readings"] + "/instruction-readings-x-g1.md", "# Readings\n")
        r = self.run_tool("grade_readings.py", self.LAYOUT["readings"] + "/instruction-readings-x-g1.md", "--check-doc")
        self.assertEqual(r.returncode, 0, r.stdout + r.stderr)

    def test_rerender_finds_the_reading_pages(self):
        self.write(self.LAYOUT["readings"] + "/instruction-readings-x-g1.md", "# Readings\n\nNo entries.\n")
        r = self.run_tool("rerender_mismatches.py", "--root", "root", "--jobs", "1")
        self.assertEqual(r.returncode, 0, r.stdout + r.stderr)
        self.assertIn("instruction-readings-x-g1.md", r.stdout)


class SetupCloneTests(Workspace):
    """setup-clone.sh finds the sibling pins."""

    def test_siblings_are_cloned_from_the_pins(self):
        base = tempfile.mkdtemp()
        self.addCleanup(shutil.rmtree, base)
        sib = os.path.join(base, "other.git")
        os.makedirs(sib)
        git = lambda cwd, *a: subprocess.run(("git", "-c", "user.name=t", "-c", "user.email=t@example.invalid",
                                              "-c", "commit.gpgsign=false", "-C", cwd) + a, check=True, capture_output=True, text=True)
        git(sib, "init", "-q")
        git(sib, "commit", "-q", "--allow-empty", "-m", "x")
        sha = git(sib, "rev-parse", "HEAD").stdout.strip()
        self.write(self.LAYOUT["config"] + "/inventory-siblings.json", json.dumps({"other": sha}))
        os.makedirs(os.path.join(self.ws, "tools"), exist_ok=True)
        shutil.copy(os.path.join(HERE, "setup-clone.sh"), os.path.join(self.ws, "tools", "setup-clone.sh"))
        git(self.ws, "init", "-q")
        shutil.rmtree(os.path.join(self.ws, "root"))
        env = dict(os.environ, SIBLING_BASE=base)
        r = subprocess.run(["sh", "tools/setup-clone.sh"], cwd=self.ws, capture_output=True, text=True, env=env)
        self.assertEqual(r.returncode, 0, r.stderr)
        self.assertIn("sibling other at %s" % sha[:12], r.stdout)
        self.assertTrue(os.path.isdir(os.path.join(self.ws, ".cache", "siblings", "other", ".git")))
        self.assertIn("references/irix-files.md", r.stdout)


if __name__ == "__main__":
    unittest.main()
