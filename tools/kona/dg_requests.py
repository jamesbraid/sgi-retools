#!/usr/bin/env python3
"""Write one row for each display-generator request of arm1.u (IRIX 6.5.30m).

Usage: dg_requests.py [UCODE_DIR] [OUT]
       defaults: ucode/KONA ucode/dg_requests.md

arm_video_cmd (token 0x1a6) reads a request number, indexes DGDispatchTable
(0x040412c0, 8-byte entries {payload word count, handler}) and calls the
handler with the payload. Per request the script reads, from arm1.u itself:

  - the table entry's two words (checked against ucode/dg_dispatch.tsv);
  - the handler's symbol and address;
  - in the handler's listing (ucode/arm1.s), each call or tail jump to
    SendDGRply, with the reply type in r0 and the byte count in r2 that
    the nearest preceding mov instructions load, when they are constants;
  - how many display-bus access sites ucode/dg_access.tsv gives the handler.

The effect column is ucode/dg_effects.tsv, written by hand from the handler
readings in ucode/arm1_functions.md.
"""
import collections
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import arm1_disasm as A  # noqa: E402

TABLE = 0x040412c0
COUNT = 93


def listing_functions(path):
    """{function: [instruction text]} from ucode/arm1.s, a label line starting each function."""
    out, cur = collections.OrderedDict(), None
    for line in open(path):
        line = line.rstrip('\n')
        m = re.match(r'^([A-Za-z_$][\w$]*):$', line)
        if m:
            cur = m.group(1)
            out.setdefault(cur, [])
            continue
        m = re.match(r'^[0-9a-f]{8}: [0-9a-f]{8}  (.*)$', line)
        if m and cur:
            out[cur].append(m.group(1))
    return out


def replies(body):
    """[(type, bytes)] for each call or tail jump to SendDGRply in a handler body; None where the
    register is not loaded by a constant mov before it."""
    got = []
    for i, t in enumerate(body):
        if re.match(r'b(l)?\w* 0x[0-9a-f]+ <SendDGRply>', t):
            ty = by = None
            for p in reversed(body[max(0, i - 12):i]):
                m = re.match(r'mov\w* (r0|r2), #(0x[0-9a-f]+|\d+)$', p)
                if m and m.group(1) == 'r0' and ty is None:
                    ty = int(m.group(2), 0)
                if m and m.group(1) == 'r2' and by is None:
                    by = int(m.group(2), 0)
            got.append((ty, by))
    return got


# Requests whose handlers are long (hundreds of instructions) and were checked only for the constants,
# registers and structure the effect names, not instruction by instruction.
LONG = set()


def main():
    src = sys.argv[1] if len(sys.argv) > 1 else 'ucode/KONA'
    out = sys.argv[2] if len(sys.argv) > 2 else 'ucode/dg_requests.md'
    mem, syms, base, ro, dbase, rw = A.load(os.path.join(src, 'arm1.u'))
    name = {}
    for v, f, n in syms:
        if base <= v < base + ro:
            name.setdefault(v, n)
    want = {}
    for line in open('ucode/dg_dispatch.tsv'):
        f = line.rstrip('\n').split('\t')
        if line.startswith('#') or f[0] == 'command':
            continue
        want[int(f[0])] = (int(f[1]), f[2])
    effect = {}
    for line in open('ucode/dg_effects.tsv'):
        f = line.rstrip('\n').split('\t')
        if line.startswith('#') or f[0] == 'request':
            continue
        effect[int(f[0])] = f[1]
    sites = collections.Counter()
    for line in open('ucode/dg_access.tsv'):
        f = line.split('\t')
        if f[0] != 'function':
            sites[f[0]] += 1
    bodies = listing_functions('ucode/arm1.s')
    rows = []
    for n in range(COUNT):
        cnt, h = mem[TABLE + 8 * n], mem[TABLE + 8 * n + 4]
        hn = name.get(h)
        if (cnt, hn) != want[n]:
            sys.exit('request %d: table holds %d words and 0x%08x (%s), dg_dispatch.tsv says %s' % (n, cnt, h, hn, want[n]))
        rp = replies(bodies.get(hn, []))
        if not rp:
            rcell = 'no reply call'
        elif len(rp) == 1 and rp[0][0] is not None:
            rcell = 'type 0x%x, %s bytes' % (rp[0][0], rp[0][1] if rp[0][1] is not None else 'variable')
        else:
            rcell = '%d `SendDGRply` calls' % len(rp)
        s = sites.get(hn, 0)
        grade = '**Inferred**' if n in LONG else '**Established**'
        rows.append('| %d | `%s` | %d payload word%s | word at 0x%08x | handler at 0x%08x | %s | %s | %s | %s |' % (
            n, hn, cnt, '' if cnt == 1 else 's', TABLE + 8 * n, h, rcell,
            '%d bus site%s' % (s, '' if s == 1 else 's') if s else '0 own bus sites', effect[n], grade))
    hdr = """# Display-generator requests one by one

Generated by `scripts/dg_requests.py` from `ucode/KONA/arm1.u`, [arm1.s](arm1.s), [dg_dispatch.tsv](dg_dispatch.tsv), [dg_access.tsv](dg_access.tsv) and [dg_effects.tsv](dg_effects.tsv); do not edit by hand. One row per request number of `DGDispatchTable` in `arm1.u` (IRIX 6.5.30m), 93 in all. How a request arrives is in [arm1_firmware.md](arm1_firmware.md) (token 0x1a6, `arm_video_cmd`), what each handler does in full is in [arm1_functions.md](arm1_functions.md#display-generator), and the requests by group with the registers they reach are in [../docs/dg.md](../docs/dg.md#display-requests).

**Established** (the table and the replies). `DGDispatchTable` at 0x040412c0 holds 93 entries of two words, the payload word count and the handler address; `arm_video_cmd` reads the request number, that many payload words and a checksum word, and calls the handler with the payload. The reply column reads the handler's listing: the type is the constant in r0 and the size the constant in r2 before its call to `SendDGRply`, and "no reply call" means the handler sends nothing back. The bus column counts the handler's own display-bus access sites in [dg_access.tsv](dg_access.tsv); a handler with none reaches the bus through its callees or only changes the firmware's records.

**Established** (effects). The effect column is a short summary of the handler's reading in [arm1_functions.md](arm1_functions.md#display-generator), kept in [dg_effects.tsv](dg_effects.tsv). Every handler was read against its listing instruction by instruction; the nine long ones (211 to 1008 listing lines each) have their own entries under [Long display requests, read in full](arm1_functions.md#long-display-requests-read-in-full).

| Request | Handler | Words | Table word | Code | Reply | Bus | Effect | Grade |
|---|---|---|---|---|---|---|---|---|
"""
    with open(out, 'w') as fh:
        fh.write(hdr)
        fh.write('\n'.join(rows) + '\n')


if __name__ == '__main__':
    main()
