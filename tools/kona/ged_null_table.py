#!/usr/bin/env python3
"""Write one row for every table B entry of the distributor program that
holds a null loop (ged1b.u, IRIX 6.5.30m).

Usage: ged_null_table.py [LISTING] [BANKS] [ROUTE] [OUT]
       defaults: ucode/ged_listing.txt ucode/ged_banks.tsv
                 ucode/ged_route.tsv ucode/ged_null_entries.md

Every input is already in the repository and was derived from the binary:
ged_listing.txt (scripts/ged_disasm.py) gives table A, the program words and
their source lines; ged_banks.tsv (scripts/ged_route.py) gives the 512 table
B words. The script reads, per entry:

  - the word the entry holds and that word's source line;
  - which (class, state, token offset) pairs form the entry's index under the
    rule of ucode/ged.md "How an entry is chosen": index = 8 x A[r48] +
    4 x state + j, j = 0 vertex, 1 material, 2 END, 3 SWAPTMESH; in the idle
    class the index is the token's entry number k itself;
  - whether any word of the class's module loads that state into r49 (a
    load0 of r49 in the listing, excluding the idle reset word 0x1d);
  - for idle entries, how many geometry-form host tokens have that k
    (ged_route.tsv).

A null loop is the pair of words at 0x003-0x005 or 0x006-0x008: a load of
r69 with geometry-engine slot 176 (mgebi_NullCommand) and a transfer back
to the load. The script checks that both loops still read that way before it
writes anything.
"""
import collections
import re
import sys

LISTING = sys.argv[1] if len(sys.argv) > 1 else 'ucode/ged_listing.txt'
BANKS = sys.argv[2] if len(sys.argv) > 2 else 'ucode/ged_banks.tsv'
ROUTE = sys.argv[3] if len(sys.argv) > 3 else 'ucode/ged_route.tsv'
OUT = sys.argv[4] if len(sys.argv) > 4 else 'ucode/ged_null_entries.md'

CLASS_NAME = {0: 'idle', 1: 'points', 2: 'lines', 4: 'triangles', 5: 'line strip', 6: 'line loop',
              7: 'quads', 8: 'quad strip', 9: 'triangle strip', 10: 'fan or polygon', 12: 'subdivision'}
J_NAME = {0: 'vertex', 1: 'material', 2: 'end token', 3: 'swap token'}
NULL = {0x003: 'dist.s:13', 0x006: 'dist.s:18'}


def read_listing(path):
    table_a, words, r48, r49 = None, {}, collections.defaultdict(set), collections.defaultdict(set)
    for ln in open(path):
        m = re.match(r'# table A \(16 words.*?\): (.*)', ln)
        if m:
            table_a = [int(x, 16) for x in m.group(1).split()]
            continue
        m = re.match(r'([0-9a-f]{3})  ([0-9a-f]{8})  (\S+):(\d+)\s+(.*)', ln)
        if not m:
            continue
        addr, src, text = int(m.group(1), 16), m.group(3), m.group(5)
        words[addr] = (int(m.group(2), 16), '%s:%s' % (src, m.group(4)), text)
        lm = re.match(r'load0 (?:[^,]*\s)?r48, 0x([0-9a-f]+)', text)
        if lm and int(lm.group(1), 16):
            r48[src].add(int(lm.group(1), 16))
        lm = re.match(r'load0 (?:[^,]*\s)?r49, 0x([0-9a-f]+)', text)
        if lm and int(lm.group(1), 16) != 0x1d:
            r49[src].add(int(lm.group(1), 16) >> 10)
    return table_a, words, r48, r49


def check_null(words):
    for a, src in NULL.items():
        w0, s0, t0 = words[a]
        w1, _, t1 = words[a + 1]
        if s0 != src or 'r69, 0xb0' not in t0 or 'mgebi_NullCommand' not in t0 \
                or not re.match(r'xfer0 r0 -> %03x\b' % a, t1):
            sys.exit('ged_null_table: the words at 0x%03x no longer read as a null loop' % a)


def main():
    table_a, words, r48, r49 = read_listing(LISTING)
    check_null(words)
    cls_of_src = {}
    for src, cs in r48.items():
        if len(cs) != 1:
            sys.exit('ged_null_table: %s loads more than one class: %s' % (src, sorted(cs)))
        cls_of_src[src] = cs.pop()
    states = collections.defaultdict(set)
    for src, ns in r49.items():
        if src in cls_of_src:
            states[cls_of_src[src]] |= ns
    base = {c: 8 * table_a[c] for c in CLASS_NAME if c}

    geo = collections.Counter()
    for ln in open(ROUTE):
        if ln.startswith('#') or ln.startswith('token\t'):
            continue
        f = ln.rstrip('\n').split('\t')
        if len(f) > 11 and f[11] == 'geometry':
            geo[int(f[4])] += 1

    rows = []
    for ln in open(BANKS):
        if ln.startswith('#') or ln.startswith('n\t'):
            continue
        n, _bank, _k, entry, src, line = ln.rstrip('\n').split('\t')
        n, entry = int(n), int(entry, 16)
        if entry not in NULL:
            continue
        forms = []
        if n < 64:
            forms.append((0, None, n))
        for c, b in sorted(base.items()):
            off = n - b
            if 0 <= off < 64:
                forms.append((c, off // 4, off % 4))
        rows.append((n, entry, '%s line %s' % (src, line), forms))

    out = []
    out.append('# Distributor table B entries that hold a null loop')
    out.append('')
    out.append('Generated by `scripts/ged_null_table.py` from [ged_listing.txt](ged_listing.txt), '
               '[ged_banks.tsv](ged_banks.tsv) and [ged_route.tsv](ged_route.tsv); do not edit by hand. '
               'One row per entry of the 512-entry table B of `ged1b.u` (IRIX 6.5.30m) whose word is one '
               'of the two null loops. The rows of every other entry are in [ged.md](ged.md#table-b-entries-one-by-one).')
    out.append('')
    out.append('**Established** (the words). The loop at 0x003-0x005 (`dist.s` lines 13-15) and the loop at '
               '0x006-0x008 (`dist.s` lines 18-20) are the same three words: a load of r69 with geometry-engine '
               'slot 176, `mgebi_NullCommand`, a transfer back to that load, and a no-op. Neither fetches nor '
               'releases, so a command that lands on one is consumed by the distributor without reaching an '
               'engine. Which loop an entry holds is read from table B itself.')
    out.append('')
    out.append('**Inferred** (where each index comes from). The columns "formed by" and "loaded states" apply the index '
               'rule of [How an entry is chosen](ged.md#how-an-entry-is-chosen): index = 8 x A[r48] + 4 x state + j, '
               'with j = 0 for a vertex, 1 material, 2 `HP_END` (the end token) and 3 `HP_SWAPTMESH` (the swap token), and in the idle class the '
               'index is the token entry number k. Every class whose 64-entry block covers the index is listed as class:state, separated by spaces (no class block covers 0x1e8-0x1ff, where the slot is read as index mod 4); all of them share the token slot j, since every block starts at a multiple of 8. '
               'A state counts as loaded when some word of that class\'s module loads it into r49 (the idle reset '
               'value 0x1d excluded). For idle entries the last column counts the geometry-form host tokens whose '
               'command number has that k; attribute tokens such as colour and normal reach the vertex record '
               'without a program step, so a null loop there is the expected entry. The effect column follows: an entry that a loaded state or a geometry token can select swallows that token; one that nothing selects is a spare slot.')
    out.append('')
    out.append('| Entry | Program | Holds | Source | Formed by (class:state) | Token kind | Loaded states | Effect | Label |')
    out.append('|---|---|---|---|---|---|---|---|---|')
    loaded_any = 0
    for n, entry, srcl, forms in rows:
        by, ld, slot = [], [], None
        for c, st, j in forms:
            if c == 0:
                by.append('idle k %d' % j)
                slot = ('%d geometry token%s' % (geo[j], '' if geo[j] == 1 else 's')) if geo[j] else 'no geometry token'
            else:
                by.append('%d:%d' % (c, st))
                if st in states[c]:
                    ld.append('%d:%d' % (c, st))
                slot = slot or J_NAME[j]
        if ld:
            loaded_any += 1
        if not forms:
            by, slot, lds = ['no block reaches 0x1e8'], J_NAME[n % 4], 'none loaded'
        elif forms[0][0] == 0:
            lds = 'idle class'
        else:
            lds = ('%s loaded' % ' '.join(ld)) if ld else 'none loaded'
        if forms and forms[0][0] == 0:
            eff = 'token consumed, nothing reaches engines' if geo[forms[0][2]] else 'unused number, no geometry sender'
        elif ld:
            eff = 'token consumed, nothing reaches engines'
        else:
            eff = 'spare slot, never selected'
        out.append('| 0x%03x | `ged1b.u` | null loop at 0x%03x | %s | %s | %s | %s | %s | **Inferred** |'
                   % (n, entry, srcl, ' '.join(by), slot, lds, eff))
    out.append('')
    out.append('%d entries. In %d of them a loaded state of some class forms the index, so a token can reach the '
               'loop there and is dropped; in the rest no loaded state forms it.' % (len(rows), loaded_any))
    out.append('')
    open(OUT, 'w').write('\n'.join(out))


if __name__ == '__main__':
    main()
