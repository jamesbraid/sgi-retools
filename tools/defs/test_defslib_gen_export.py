#!/usr/bin/env python3
"""Tests for the export profiles: the Rust constants, the C field macros, the commit banner and the checks."""
import os
import re
import subprocess
import sys
import unittest

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from defslib import gen, gen_export, loader  # noqa: E402
from testkit import CurrentRepoTest, HERE, RepoTest, which  # noqa: E402

GEN = os.path.join(HERE, "defs-gen")
CHECK = os.path.join(HERE, "defs-check")
CC = which("cc", "gcc")
RUSTC = which("rustc")
SETTINGS = '\n[gen.export]\nprofiles = ["rust-regs", "c-regfields"]\n\n[gen.export.units.uart]\nbase = 0x10\n'


def run(tool, *args):
    return subprocess.run([sys.executable, tool, *args], capture_output=True, text=True)


class ExportTest(RepoTest):
    def enable(self, extra=""):
        self.write("defs/check.toml", self.read("defs/check.toml") + SETTINGS + extra)

    def render(self):
        repo = loader.load_repo(self.root)
        self.assertEqual(repo.errors, [])
        files, errors = gen.render(repo)
        self.assertEqual(errors, [])
        return files

    def test_nothing_is_written_unless_the_settings_ask(self):
        files = self.render()
        self.assertFalse([f for f in files if "rust-regs" in f or "c-regfields" in f])

    def test_rust_regs_shape(self):
        self.enable()
        text = self.render()["gen/rust-regs/uart.rs"]
        lines = text.splitlines()
        self.assertRegex(lines[0], r"^// @generated by defs-gen from \w+ at (?:[0-9a-f]{40}|unknown) - do not edit")
        self.assertEqual(lines[1:3], ["regs! {", "    base 0x10;"])
        self.assertEqual(lines[-1], "}")
        ctl = [ln for ln in lines if ln.startswith("    CTL ")][0]
        self.assertTrue(ctl.startswith("    CTL 0x0000 rw width 32 reset 0x0 { "), ctl)
        self.assertIn("DIVISOR: 16..31", ctl)           # inclusive bit range, low to high
        self.assertTrue(ctl.endswith(" };"), ctl)       # every register ends in a semicolon, fields or not
        data = [ln for ln in lines if ln.startswith("    DATA ")][0]
        self.assertIn("DATA 0x0110 ", data)             # relative to the base: 0x120 - 0x10
        self.assertIn("width 8 count 16 stride 0x1", data)

    def test_rust_regs_leave_out_what_is_not_a_register(self):
        self.enable()
        text = self.render()["gen/rust-regs/uart.rs"]
        status = [ln for ln in text.splitlines() if ln.startswith("    STATUS ")][0]
        self.assertNotIn("reset", status)         # reset unknown: no value, not a made-up zero
        self.assertTrue(status.endswith(" };"), status)
        self.assertTrue(text.splitlines()[-2].endswith(";"), text)    # the last register ends in a semicolon
        for banned in ("pub ", "//!", "///", "enum Value", "FIFO_DEPTH", "#[test]", "Control register", "established", "inferred"):
            self.assertNotIn(banned, text)

    def test_rust_regs_wrap_a_long_register_one_field_per_line(self):
        self.enable()
        many = "\n".join('f%d = { bits = [%d, %d], grade = "unknown" }' % (i, i, i) for i in range(40))
        self.edit("defs/uart.toml", "[registers.data]", '[registers.wide]\noffset = 0x300\naccess = "rw"\nwidth = 64\ngrade = "unknown"\n\n[registers.wide.fields]\n%s\n\n[registers.data]' % many)
        text = self.render()["gen/rust-regs/uart.rs"]
        self.assertIn("    WIDE 0x02f0 rw {\n        F39: 39..39,\n        F38: 38..38,\n", text)
        self.assertIn("\n    };\n", text)               # the wrapped register closes with a semicolon

    def test_named_constants_are_carried_and_unnamed_ones_are_not(self):
        self.enable('constants = ["FIFO_DEPTH"]\n')
        self.assertIn("    const FIFO_DEPTH 0x10;", self.render()["gen/rust-regs/uart.rs"])
        self.edit("defs/check.toml", 'constants = ["FIFO_DEPTH"]\n', "")
        self.assertNotIn("FIFO_DEPTH", self.render()["gen/rust-regs/uart.rs"])

    def test_a_named_constant_the_unit_lacks_is_an_error(self):
        self.enable('constants = ["NOPE"]\n')
        _, errors = gen.render(loader.load_repo(self.root))
        self.assertTrue([e for e in errors if "NOPE" in e])

    def test_banner_names_the_source_setting(self):
        self.enable()
        self.edit("defs/check.toml", "[gen.export]\n", '[gen.export]\nsource = "example.org/some/repo"\n')
        files = self.render()
        self.assertIn("from example.org/some/repo at ", files["gen/rust-regs/uart.rs"].splitlines()[0])
        self.assertNotIn("example.org", files["gen/c-regfields/uart.h"])     # the C export is unchanged

    def test_reset_grade_is_not_written(self):
        self.enable()
        self.edit("defs/uart.toml", "reset = 0\nreset_from = \"fixture notes (reset table)\"\n", 'reset = 0x5\nreset_grade = "inferred"\n')
        text = self.render()["gen/rust-regs/uart.rs"]
        self.assertIn("reset 0x5", text)
        self.assertNotIn("inferred", text)

    def test_c_regfields_shape(self):
        self.enable()
        text = self.render()["gen/c-regfields/uart.h"]
        self.assertTrue(text.startswith("/* @generated by defs-gen from "))
        self.assertIn("#define UART_BASE 0x10", text)
        self.assertIn("REG32(CTL, 0x0)", text)
        self.assertIn("FIELD(CTL, DIVISOR, 16, 16)", text)
        self.assertIn("REG8(DATA, 0x110)", text)
        self.assertIn("#define DATA_COUNT 16", text)
        self.assertNotIn("registerfields", text)     # the generated header must not name another header

    def test_base_above_a_register_is_an_error(self):
        self.enable()
        self.edit("defs/check.toml", "base = 0x10", "base = 0x11")
        files, errors = gen.render(loader.load_repo(self.root))
        self.assertTrue(any("below the export base" in e for e in errors), errors)

    def test_unknown_unit_and_unknown_profile(self):
        self.enable('\n[gen.export.units.nosuch]\nbase = 0\n')
        _files, errors = gen.render(loader.load_repo(self.root))
        self.assertTrue(any("nosuch: not a unit" in e for e in errors), errors)
        self.edit("defs/check.toml", '"c-regfields"]', '"c-regfields", "elsewhere"]')
        self.assertTrue(any("gen.export.profiles[2]" in e for e in loader.load_repo(self.root).errors))

    def test_commit_is_masked_when_comparing(self):
        self.enable()
        a = "// @generated by defs-gen from x at " + "a" * 40 + " - do not edit, change the source\nbody\n"
        b = a.replace("a" * 40, "b" * 40)
        self.assertEqual(gen_export.mask_commit(a), gen_export.mask_commit(b))
        self.assertNotEqual(gen_export.mask_commit(a), gen_export.mask_commit(b.replace("body", "other")))

    def test_check_ignores_the_commit_and_catches_content(self):
        self.enable()
        self.assertEqual(run(GEN, "--root", self.root).returncode, 0)
        path = self.path("gen/rust-regs/uart.rs")
        old = self.read("gen/rust-regs/uart.rs")
        self.write("gen/rust-regs/uart.rs", re.sub(r" at [0-9a-f]{40} ", " at " + "c" * 40 + " ", old))
        r = run(GEN, "--root", self.root, "--check")
        self.assertEqual(r.returncode, 0, r.stdout)
        before = os.stat(path).st_mtime_ns
        self.assertEqual(run(GEN, "--root", self.root).returncode, 0)
        self.assertEqual(os.stat(path).st_mtime_ns, before)     # a rewrite would only change the commit: left alone
        self.write("gen/rust-regs/uart.rs", self.read("gen/rust-regs/uart.rs").replace("0x0110", "0x0111"))
        r = run(GEN, "--root", self.root, "--check")
        self.assertEqual(r.returncode, 1)
        self.assertIn("gen/rust-regs/uart.rs: stale", r.stdout)

    def test_profile_flag_scopes_the_run(self):
        self.enable()
        self.assertEqual(run(GEN, "--root", self.root, "--profile", "c-regfields").returncode, 0)
        self.assertTrue(os.path.isfile(self.path("gen/c-regfields/uart.h")))
        self.assertFalse(os.path.exists(self.path("gen/rust-regs")))
        self.assertFalse(os.path.exists(self.path("gen/c/uart.h")))
        self.assertEqual(run(GEN, "--root", self.root, "--profile", "c-regfields", "--check").returncode, 0)
        self.assertEqual(run(GEN, "--root", self.root, "--profile", "rust-regs", "--check").returncode, 1)

    def test_profile_flag_needs_the_setting(self):
        r = run(GEN, "--root", self.root, "--profile", "rust-regs")
        self.assertEqual(r.returncode, 2)
        self.assertIn("not enabled", r.stderr)

    def test_removed_unit_output_is_pruned(self):
        self.enable()
        self.assertEqual(run(GEN, "--root", self.root).returncode, 0)
        self.edit("defs/check.toml", "[gen.export.units.uart]\nbase = 0x10\n", "")
        self.assertEqual(run(GEN, "--root", self.root).returncode, 0)
        self.assertFalse(os.path.exists(self.path("gen/rust-regs/uart.rs")))
        self.assertFalse(os.path.exists(self.path("gen/c-regfields/uart.h")))

    # -- checks ---------------------------------------------------------
    def check_fails(self, needle):
        self.assertEqual(run(GEN, "--root", self.root).returncode, 0)
        r = run(CHECK, "--root", self.root)
        self.assertEqual(r.returncode, 1, r.stdout + r.stderr)
        self.assertIn(needle, r.stdout)

    def test_clean_export_passes_the_checks(self):
        self.enable()
        self.assertEqual(run(GEN, "--root", self.root).returncode, 0)
        r = run(CHECK, "--root", self.root)
        self.assertEqual(r.returncode, 0, r.stdout + r.stderr)

    def test_leak_in_an_export_is_caught(self):
        self.enable()
        # lower case in the Rust, upper case in the C: the board-token rule sees it in the C header
        self.edit("defs/uart.toml", "[registers.data]", '[registers.ip27]\noffset = 0x200\naccess = "rw"\nwidth = 32\ngrade = "unknown"\n\n[registers.data]')
        self.assertEqual(run(GEN, "--root", self.root).returncode, 0)
        r = run(CHECK, "--root", self.root)
        self.assertEqual(r.returncode, 1, r.stdout)
        self.assertIn("c-regfields/uart.h", r.stdout)

    def test_project_name_outside_the_banner_is_caught_in_export_rust(self):
        self.enable()
        self.edit("defs/uart.toml", 'rx_ready = { bits = [0, 0]', 'mini = { bits = [9, 9], grade = "unknown" }\nrx_ready = { bits = [0, 0]')
        self.write("defs/check.toml", self.read("defs/check.toml").replace('name = "mini"', 'name = "mini"') if "[project]" in self.read("defs/check.toml") else "[project]\nname = \"mini\"\n" + self.read("defs/check.toml"))
        self.assertEqual(run(GEN, "--root", self.root).returncode, 0)
        r = run(CHECK, "--root", self.root)
        self.assertEqual(r.returncode, 1, r.stdout)
        self.assertIn("project name in generated Rust", r.stdout)
        # the banner line itself names the project and is not reported
        self.assertNotIn("rust-regs/uart.rs:1:", r.stdout)

    def test_an_edited_banner_is_stale(self):
        self.enable()
        self.assertEqual(run(GEN, "--root", self.root).returncode, 0)
        p = "gen/rust-regs/uart.rs"
        self.write(p, self.read(p).replace("do not edit, change the source", "do not edit"))
        r = run(CHECK, "--root", self.root)
        self.assertEqual(r.returncode, 1, r.stdout)
        self.assertIn("gen/rust-regs/uart.rs: stale", r.stdout)

    @unittest.skipUnless(CC and RUSTC, "needs a C compiler and rustc; run in the CI container")
    def test_build_compiles_both_exports(self):
        self.enable()
        self.assertEqual(run(GEN, "--root", self.root).returncode, 0)
        r = run(CHECK, "--root", self.root, "--build")
        self.assertEqual(r.returncode, 0, r.stdout + r.stderr)
        self.assertIn("build: ok", r.stdout)

    @unittest.skipUnless(CC, "needs a C compiler")
    def test_build_catches_a_broken_c_export(self):
        self.enable()
        self.assertEqual(run(GEN, "--root", self.root).returncode, 0)
        p = "gen/c-regfields/uart.h"
        self.write(p, self.read(p).replace("REG32(CTL, 0x0)", "REG32(CTL, 0x4)"))
        r = run(CHECK, "--root", self.root, "--build", "--no-fresh")
        self.assertEqual(r.returncode, 1, r.stdout + r.stderr)
        self.assertIn("c-regfields/uart.h: C compile failed", r.stdout)


class ExportCurrentLayoutTest(CurrentRepoTest):
    def test_files_land_under_generated(self):
        self.write("tools/config/defs-check.toml", self.read("tools/config/defs-check.toml") + SETTINGS)
        repo = loader.load_repo(self.root)
        self.assertEqual(repo.errors, [])
        files, errors = gen.render(repo)
        self.assertEqual(errors, [])
        self.assertIn("generated/rust-regs/uart.rs", files)
        self.assertIn("generated/c-regfields/uart.h", files)
        self.assertEqual(run(GEN, "--root", self.root).returncode, 0)
        self.assertEqual(run(CHECK, "--root", self.root).returncode, 0)


if __name__ == "__main__":
    unittest.main()
