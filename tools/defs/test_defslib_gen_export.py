SETTINGS = '\n[gen.export]\nprofiles = ["rust-regs", "c-regfields"]\n\n[gen.export.units.uart]\nbase = 0x10\n'


def unstamp(text):
    """The text without the stamp lines (licence, generator version, input hash) after the banner."""
    return "\n".join(ln for ln in text.splitlines() if not re.match(r"^(?:/\* |// )(?:SPDX-License|defs-gen \d|input sha256)", ln)) + "\n"


def run(tool, *args):
    return subprocess.run([sys.executable, tool, *args], capture_output=True, text=True)


class ExportTest(RepoTest):
    def enable(self, extra=""):
        self.write("defs/check.toml", self.read("defs/check.toml") + SETTINGS + extra)

    def render(self):
        repo = loader.load_repo(self.root)
        self.assertEqual(repo.errors, [])
        files, errors = gen.render(repo)
        self.assertEqual(errors, [])
        return files

    def test_nothing_is_written_unless_the_settings_ask(self):
        files = self.render()
        self.assertFalse([f for f in files if "rust-regs" in f or "c-regfields" in f])

    def test_rust_regs_shape(self):
        self.enable()
        text = unstamp(self.render()["gen/rust-regs/uart.rs"])
        lines = text.splitlines()
        self.assertRegex(lines[0], r"^// @generated by defs-gen from \w+ at (?:[0-9a-f]{40}|unknown) - do not edit")
        self.assertEqual(lines[1:3], ["regs! {", "    base 0x10;"])
        self.assertEqual(lines[-1], "}")
        self.assertIn("    STATUS 0x0004 width 32 { RX_READY: 0..0 };", lines)     # no reset in the map: none written
        data = [ln for ln in lines if ln.startswith("    DATA ")][0]
        self.assertEqual(data, "    DATA 0x0110 width 8 count 16 stride 0x1 end 0x120;")    # relative to the base; 0x110 + 16 * 1
        for word in ("established", "inferred", "Control register", " rw", "FIFO_DEPTH"):
            self.assertNotIn(word, text)        # no grades, prose, access letters or unselected constants

    def test_reset_is_written_only_when_known(self):
        self.enable()
        lines = self.render()["gen/rust-regs/uart.rs"].splitlines()
        self.assertTrue([ln for ln in lines if ln.startswith("    CTL 0x0000 width 32 reset 0x0 ")])
        self.assertFalse([ln for ln in lines if "STATUS" in ln and "reset" in ln])

    def test_masks_are_written_in_order_and_zero_is_left_out(self):
        self.enable()
        self.edit("defs/uart.toml", 'access = "rw"\nwidth = 32\nreset = 0\n', 'access = "rw"\nwidth = 32\nreset = 0\nrsvd = 0xf000\nro = 0x1\nw1c = 0x6\ncor = 0\n')
        ctl = [ln for ln in self.render()["gen/rust-regs/uart.rs"].splitlines() if ln.startswith("    CTL ")][0]
        self.assertTrue(ctl.startswith("    CTL 0x0000 width 32 reset 0x0 ro 0x1 w1c 0x6 rsvd 0xf000 {"), ctl)
        self.assertNotIn("cor", ctl)

    def test_fields_and_values(self):
        self.enable()
        ctl = self.render()["gen/rust-regs/uart.rs"]     # the CTL line is long, so one field per line
        self.assertIn("        DIVISOR: 16..31,", ctl)
        self.assertIn("PARITY: 1..3 { NONE = 0, ODD = 1, EVEN = 2 },", ctl)     


    def test_a_field_value_above_255_is_an_error(self):
        self.enable()
        self.edit("defs/uart.toml", "even = { value = 2,", "even = { value = 256,")
        _files, errors = gen.render(loader.load_repo(self.root))
        self.assertTrue(any("above 255" in e for e in errors), errors)

    def test_only_selected_constants_are_written(self):
        self.enable()
        self.edit("defs/check.toml", "base = 0x10\n", 'base = 0x10\nconstants = ["FIFO_DEPTH"]\n')
        lines = unstamp(self.render()["gen/rust-regs/uart.rs"]).splitlines()
        self.assertEqual(lines[3], "    const FIFO_DEPTH = 0x10;")
        self.edit("defs/check.toml", '"FIFO_DEPTH"', '"NOSUCH"')
        _files, errors = gen.render(loader.load_repo(self.root))
        self.assertTrue(any("NOSUCH" in e for e in errors), errors)

    def test_banner_names_the_source_setting(self):
        self.enable()
        self.edit("defs/check.toml", "[gen.export]\n", '[gen.export]\nsource = "example.org/some/repo"\n')
        files = self.render()
        self.assertIn("from example.org/some/repo at ", files["gen/rust-regs/uart.rs"].splitlines()[0])
        self.assertNotIn("example.org", files["gen/c-regfields/uart.h"])     # the C export is unchanged

    def test_c_regfields_shape(self):
        self.enable()
        text = self.render()["gen/c-regfields/uart.h"]
        self.assertTrue(text.startswith("/* @generated by defs-gen from "))
        self.assertIn("#define UART_BASE 0x10", text)
        self.assertIn("REG32(UART_CTL, 0x0)", text)
        self.assertIn("FIELD(UART_CTL, DIVISOR, 16, 16)", text)
        self.assertIn("REG8(UART_DATA, 0x110)", text)
        self.assertIn("#define UART_DATA_COUNT 16", text)
        self.assertNotIn("registerfields", text)     # the generated header must not name another header

    def test_c_regfields_carries_every_constant(self):
        self.enable()
        self.edit("defs/uart.toml", "[constants]", '[constants]\nWINDOW = { value = 0x100, count = 4, stride = 8, grade = "unknown" }\n'
                  'FAR = { value = 0x1ffffffff, grade = "inferred", macro = "UART_FAR_BASE" }')
        text = self.render()["gen/c-regfields/uart.h"]
        self.assertIn("#define UART_FIFO_DEPTH                              0x10u /* established */", text)
        self.assertIn("(0x100u + (i) * 8)", text)
        self.assertIn("#define UART_WINDOW_COUNT 4", text)
        self.assertIn("/* inferred */\n#define UART_FAR_BASE                                0x1ffffffffull\n", text)     # the grade moved up: the line passed 80

    def test_c_regfields_constant_named_like_a_register_is_an_error(self):
        self.enable()
        self.edit("defs/uart.toml", "[constants]", '[constants]\nCTL = { value = 1, grade = "unknown", macro = "UART_CTL" }')
        _files, errors = gen.render(loader.load_repo(self.root))
        self.assertTrue([e for e in errors if "UART_CTL" in e], errors)

    @unittest.skipUnless(CC, "needs a C compiler")
    def test_c_regfields_two_units_sharing_a_register_name_compile_together(self):
        self.write("defs/pad.toml", self.PAD % "ctl")
        self.enable('\n[gen.export.units.pad]\nbase = 0x10\n')
        files = self.render()
        src = "".join('#include "%s"\n' % os.path.basename(f) for f in ("uart.h", "pad.h"))
        src += "int main(void) { return A_UART_CTL == A_PAD_CTL ? 0 : 1; }\n"
        for rel in ("gen/c-regfields/uart.h", "gen/c-regfields/pad.h"):
            self.write(rel, files[rel])
        self.write("gen/c-regfields/shim.h", C_SHIM)
        self.write("gen/c-regfields/t.c", '#include "shim.h"\n' + src)
        r = subprocess.run([CC, "-Werror", "-I", self.path("gen/c-regfields"), "-o", self.path("t"), self.path("gen/c-regfields/t.c")],
                           capture_output=True, text=True)
        self.assertEqual(r.returncode, 0, r.stderr)

    def test_c_regfields_base_constant_replaces_a_zero_base(self):
        self.enable()
        self.edit("defs/check.toml", "base = 0x10", "base = 0")
        self.edit("defs/uart.toml", "[constants]", '[constants]\nBASE = { value = 0xc6000000, grade = "established" }')
        self.edit("defs/uart.toml", "offset = 0x10", "offset = 0")
        text = self.render()["gen/c-regfields/uart.h"]
        self.assertEqual(text.count("#define UART_BASE"), 1)
        self.assertRegex(text, r"#define UART_BASE +0xc6000000u")

    def test_c_regfields_base_constant_clashing_with_a_set_base_is_an_error(self):
        self.enable()
