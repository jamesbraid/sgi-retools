    def test_units_naming_one_rust_file_share_it(self):
        files, errors = self.merge("extra")
        self.assertEqual(errors, [])
        both = files["gen/rust-regs/both.rs"]
        self.assertEqual(both.count("regs! {"), 1)
        self.assertIn("    CTL 0x0000 width 32 reset 0x0 ", both)
        self.assertIn("    EXTRA 0x03f0 width 32;", both)
        self.assertNotIn("gen/rust-regs/uart.rs", files)
        self.assertIn("gen/c-regfields/pad.h", files)       # the C header stays one per unit

    def test_a_name_in_two_merged_units_is_an_error(self):
        _files, errors = self.merge("ctl")
        self.assertTrue(any("CTL is defined by both" in e for e in errors), errors)

    def test_units_on_different_bases_become_blocks(self):
        self.write("defs/pad.toml", self.PAD % "ctl")      # the same name in two blocks is fine
        self.enable('rust_file = "chip"\n\n[gen.export.units.pad]\nbase = 0x20\nrust_file = "chip"\nconstants = []\n')
        files, errors = gen.render(loader.load_repo(self.root))
        self.assertEqual(errors, [])
        lines = unstamp(files["gen/rust-regs/chip.rs"]).splitlines()
        self.assertEqual(lines[1], "regs! {")
        self.assertNotIn("    base 0x10;", lines)
        self.assertEqual(lines.index("    unit pad base 0x20 {") + 1, lines.index("        CTL 0x03e0 width 32;"))
        self.assertIn("    unit uart base 0x10 {", lines)
        self.assertEqual(lines.count("    }"), 2)
        self.assertEqual(lines[-1], "}")

