DEFINE_RE = re.compile(r"^#define[ \t]+(\S+)[ \t]+((?:[^\n]*\\\n)*[^\n]*)", re.M)


def defines(text):
    """{macro name: value} of every #define, with comments dropped and a backslash continuation joined."""
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    return {m.group(1): " ".join(m.group(2).replace("\\\n", " ").split()) for m in DEFINE_RE.finditer(text)
            if not m.group(1).endswith("_H")}      # the include guards differ on purpose


class CleanProfileTest(RepoTest):
    def render(self):
        self.write("defs/check.toml", self.read("defs/check.toml") + SETTINGS.replace('"c-regfields"', '"c-clean"') + 'profiles = ["c-clean"]\n')
        repo = loader.load_repo(self.root)
        self.assertEqual(repo.errors, [])
        files, errors = gen.render(repo)
        self.assertEqual(errors, [])
        return files

    def test_same_defines_as_the_standard_header(self):
        files = self.render()
        std, clean = defines(files["gen/c/uart.h"]), defines(files["gen/c-clean/uart.h"])
        self.assertIn("UART_CTL_OFFSET", std)
        self.assertIn("UART_DATA_STRIDE", std)
        self.assertEqual(clean, std)
        self.assertEqual(sorted(std.items()), sorted(clean.items()))

    def test_no_prose_and_a_banner(self):
        files = self.render()
        std, clean = files["gen/c/uart.h"], unstamp(files["gen/c-clean/uart.h"])
        banner = clean[:clean.index("*/") + 2].replace("\n * ", " ")      # the commit can wrap the comment
        self.assertRegex(banner, r"^/\* @generated by defs-gen from \w+ at (?:[0-9a-f]{40}|unknown) \*/$")
        self.assertIn("Control register", std)
        for word in ("Control register", "established", "inferred", "uart.toml", "reset ", "fixture notes"):
            self.assertNotIn(word, clean)
        for ln in clean.splitlines()[1:]:
            if "/*" in ln and not ln.startswith("#endif"):
                self.assertRegex(ln, r"^/\* \w+ \*/$")      # one name per register, nothing else

    def test_banners_wrap_at_80_and_the_commit_stays_maskable(self):
        m = loader.load_repo(self.root).units["uart"].model
        sha = "0123456789abcdef" * 2 + "01234567"
        clean = gen_c.gen_c(m, None, clean="\n".join(gen_export.wrap_comment(
            "@generated by defs-gen from retools at " + sha)))[0]
        regfields = gen_export.gen_c_regfields(m, 0, "retools", sha)
        for text in (clean, regfields):
            self.assertEqual([ln for ln in text.splitlines() if len(ln) > 80 and not ln.startswith(("#define", "/* input sha256"))], [])
            self.assertIn(sha, text)
            self.assertNotIn(sha, gen_export.mask_commit(text))
            self.assertEqual(gen_export.mask_commit(text), gen_export.mask_commit(text.replace(sha, "f" * 40)))

    def test_masking_ignores_where_the_banner_breaks(self):
        m = loader.load_repo(self.root).units["uart"].model
        sha = "0123456789abcdef" * 2 + "01234567"
        for project in ("retools", "a-much-longer-project-name-for-the-banner"):
            clean = lambda c: gen_c.gen_c(m, None, clean="\n".join(gen_export.wrap_comment(      # noqa: E731
                "@generated by defs-gen from %s at %s" % (project, c))))[0]
            regf = lambda c: gen_export.gen_c_regfields(m, 0, project, c)                       # noqa: E731
            for make in (clean, regf):
                self.assertNotEqual(make(sha), make("unknown"))
                self.assertEqual(gen_export.mask_commit(make(sha)), gen_export.mask_commit(make("unknown")))

    def test_a_unit_gets_c_clean_only_by_asking(self):
        self.write("defs/check.toml", self.read("defs/check.toml") + SETTINGS.replace('"c-regfields"', '"c-clean"'))
