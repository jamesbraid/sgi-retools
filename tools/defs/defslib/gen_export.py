"""Export profiles: a second, smaller rendering of chosen units for a consumer that wants constants and
field macros only, with no accessors, prose or test vectors.

  rust-regs     <gen>/rust-regs/<unit>.rs     one `regs! { ... }` invocation: a line per register (offset, access,
                                              width when not 64, count and stride for an array, reset when known)
                                              with its fields as inclusive bit ranges. The consumer holds the macro.
  c-regfields   <gen>/c-regfields/<unit>.h    REG8/16/32/64 and FIELD macros in the registerfields.h style

A unit is a block: the settings give it a `base`, and every OFFSET is relative to it (BASE + OFFSET is the
offset in the unit's own address space). The settings are in defs-check.toml:

  [gen.export]
  profiles = ["rust-regs", "c-regfields"]
  source = "example.org/some/repo"    # what the rust-regs banner names; default: the project name
  [gen.export.units.some_unit]
  base = 0x780000
  constants = ["SOME_CONSTANT"]       # optional: constants of the unit to carry into rust-regs, by name

The first line of every file is an `@generated` banner naming the source repository (the `source` setting for
rust-regs, else the project) and the commit the sources were read at. The commit is the one thing that changes without the content changing, so staleness
is compared with it masked (see mask_commit): a file is stale when anything else differs.
"""
import re
import subprocess

from .genutil import GenError, one_line
from .gen_rust import rid
from .model import block_of, mask

RUST_DIR, C_DIR = "rust-regs", "c-regfields"
COMMIT_RE = re.compile(r"(@generated by defs-gen from \S+ at )(?:[0-9a-f]{40}|unknown)")
WIDE = {8: "REG8", 16: "REG16", 32: "REG32", 64: "REG64"}
WRAP = 100          # a rust-regs register line longer than this puts each field on its own line


def mask_commit(text):
    return COMMIT_RE.sub(r"\1-", text)


def source_commit(root):
    """The commit the sources are read at, or "unknown" outside a git work tree."""
    try:
        r = subprocess.run(["git", "-C", root, "rev-parse", "HEAD"], capture_output=True, text=True, timeout=30)
    except (OSError, subprocess.SubprocessError):
        return "unknown"
    out = r.stdout.strip()
    return out if r.returncode == 0 and re.fullmatch(r"[0-9a-f]{40}", out) else "unknown"


def export_banner(project, commit, comment_open, comment_close=""):
    return "%s @generated by defs-gen from %s at %s - do not edit, change the source%s" % (
        comment_open, project, commit, comment_close)


def unit_base(m, cfg):
    """The block base for a unit, checked against every register the unit has."""
    base = cfg.get("base", 0)
    for n, r in m["registers"].items():
        if r["offset"] < base:
            raise GenError("%s: register %s at 0x%x is below the export base 0x%x" % (m["unit"], n, r["offset"], base))
    return base


def _named_constants(m, names):
    """The constants a unit's export setting names, in the setting's order. A name the unit lacks is an error."""
    out = []
    for n in names:
        if n not in m["constants"]:
            raise GenError("%s: export constants name %s, which the unit does not define" % (m["unit"], n))
        out.append((n, m["constants"][n]))
    return out


def gen_rust_regs(m, base, source, commit, names=()):
    """One `regs!` invocation for the whole unit. Grades, prose and the unit's other constants are not written:
    they stay in the register map and its reference page."""
    out = [export_banner(source, commit, "//"), "regs! {", "    base 0x%x;" % base]
    for n, c in _named_constants(m, names):
        out.append("    const %s 0x%x;" % (n.upper(), c["value"]))
    for n, r in m["registers"].items():
        parts = ["%s 0x%04x %s" % (n.upper(), r["offset"] - base, r["access"])]
        if r["width"] != 64:
            parts.append("width %d" % r["width"])
        if r["count"] > 1:
            parts.append("count %d stride 0x%x" % (r["count"], r["stride"]))
        if isinstance(r["reset"], int):
            parts.append("reset 0x%x" % r["reset"])
        if r["fields"]:
            fl = ["%s: %d..%d" % (fn.upper(), f["bits"][1], f["bits"][0]) for fn, f in r["fields"].items()]
            line = "    %s { %s }" % (" ".join(parts), ", ".join(fl))
            if len(line) <= WRAP:
                out.append(line + ";")
            else:               # a register with many fields: one line per field
                out.append("    %s {" % " ".join(parts))
                out.extend("        %s," % f for f in fl)
                out.append("    };")
        else:
            out.append("    %s;" % " ".join(parts))
    out.append("}")
    return "\n".join(out) + "\n"


def gen_c_regfields(m, base, project, commit):
    blk = block_of(m)
    guard = "%s_REGFIELDS_H" % m["prefix"]
    out = [export_banner(project, commit, "/*", " */"),
           "/* %s */" % one_line(m.get("title") or m["unit"]),
           "/* Needs REG8, REG16, REG32, REG64 (name, offset) and FIELD (register, field, shift, length) defined by the",
           " * includer. Offsets are relative to %s_BASE. A comment gives each grade. */" % blk,
           "#ifndef %s\n#define %s\n" % (guard, guard),
           "#define %s_BASE 0x%x" % (blk, base)]
    for n, r in m["registers"].items():
        name = n.upper()
        out.append("")
        out.append("/* %s */" % r["grade"])
        out.append("%s(%s, 0x%x)" % (WIDE[r["width"]], name, r["offset"] - base))
        if r["count"] > 1:
            out.append("#define %s_COUNT %d" % (name, r["count"]))
            out.append("#define %s_STRIDE 0x%x" % (name, r["stride"]))
        for fn, f in r["fields"].items():
            hi, lo = f["bits"]
            out.append("FIELD(%s, %s, %d, %d)" % (name, fn.upper(), lo, hi - lo + 1))
    out.append("\n#endif /* %s */" % guard)
    return "\n".join(out) + "\n"


def render_export(repo, models, commit):
    """Return ({relative path: text}, [errors]) for the export profiles the settings ask for.
    `models` maps a unit name to the model the committed profile renders."""
    cfg = repo.settings.get("gen", {}).get("export", {})
    profiles, units = cfg.get("profiles", []), cfg.get("units", {})
    files, errors = {}, []
    if not profiles:
        if units:
            errors.append("gen.export.units is set but gen.export.profiles is empty")
        return files, errors
    lay = repo.layout
    for name in sorted(units):
        if name not in models:
            errors.append("gen.export.units.%s: not a unit" % name)
            continue
        try:
            base = unit_base(models[name], units[name])
            if RUST_DIR in profiles:
                files["%s/%s/%s.rs" % (lay.gen_root(), RUST_DIR, name)] = gen_rust_regs(
                    models[name], base, cfg.get("source") or repo.project, commit, units[name].get("constants", ()))
            if C_DIR in profiles:
                files["%s/%s/%s.h" % (lay.gen_root(), C_DIR, name)] = gen_c_regfields(models[name], base, repo.project, commit)
        except GenError as e:
            errors.append(str(e))
    return files, errors


def export_dirs(repo):
    root = repo.layout.gen_root()
    return ["%s/%s" % (root, d) for d in (RUST_DIR, C_DIR)]
