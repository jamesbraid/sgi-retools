"""Export profiles: a second, smaller rendering of chosen units for a consumer that wants constants and
field macros only, with no accessors, prose or test vectors.

  rust-regs     <gen>/rust-regs/<unit>.rs     one `regs! { ... }` invocation: a line per register (offset, width,
                                              reset and access masks when known, array bounds, fields) in QEMU's
                                              register vocabulary. The consumer holds the macro.
  c-regfields   <gen>/c-regfields/<unit>.h    REG8/16/32/64 and FIELD macros in the registerfields.h style

A unit is a block: the settings give it a `base`, and every OFFSET is relative to it (BASE + OFFSET is the
offset in the unit's own address space). The settings are in defs-check.toml:

  [gen.export]
  profiles = ["rust-regs", "c-regfields"]
  source = "example.org/some/repo"    # what the rust-regs banner names; default: the project name
  [gen.export.units.some_unit]
  base = 0x780000
  constants = ["SOME_CONSTANT"]       # optional: constants of the unit to carry into rust-regs, by name
  rust_file = "some_block"            # optional: write the unit's rust-regs into <gen>/rust-regs/some_block.rs

Units that name the same `rust_file` share one `regs!` invocation, in unit-name order. On one `base` they are
merged flat, and a register or constant name defined twice is an error that names both units. On several bases each
unit becomes a `unit NAME base N { }` block. The C header is still one per unit.

The first line of every file is an `@generated` banner naming the source repository (the `source` setting for
rust-regs, else the project) and the commit the sources were read at. The commit is the one thing that changes without the content changing, so staleness
is compared with it masked (see mask_commit): a file is stale when anything else differs.
"""
import re
import subprocess

from .genutil import GenError, one_line
from .gen_rust import rid
from .model import block_of, enum_values

RUST_DIR, C_DIR = "rust-regs", "c-regfields"
COMMIT_RE = re.compile(r"(@generated by defs-gen from \S+ at )(?:[0-9a-f]{40}|unknown)")
WIDE = {8: "REG8", 16: "REG16", 32: "REG32", 64: "REG64"}
MASKS = ("ro", "w1c", "cor", "rsvd")
WRAP = 100          # a rust-regs register line longer than this puts each field on its own line


def mask_commit(text):
    return COMMIT_RE.sub(r"\1-", text)


def source_commit(root):
    """The commit the sources are read at, or "unknown" outside a git work tree."""
    try:
        r = subprocess.run(["git", "-C", root, "rev-parse", "HEAD"], capture_output=True, text=True, timeout=30)
    except (OSError, subprocess.SubprocessError):
        return "unknown"
    out = r.stdout.strip()
    return out if r.returncode == 0 and re.fullmatch(r"[0-9a-f]{40}", out) else "unknown"


def export_banner(project, commit, comment_open, comment_close=""):
    return "%s @generated by defs-gen from %s at %s - do not edit, change the source%s" % (
        comment_open, project, commit, comment_close)


def unit_base(m, cfg):
    """The block base for a unit, checked against every register the unit has."""
    base = cfg.get("base", 0)
    for n, r in m["registers"].items():
        if r["offset"] < base:
            raise GenError("%s: register %s at 0x%x is below the export base 0x%x" % (m["unit"], n, r["offset"], base))
    return base


def _named_constants(m, names):
    """The constants a unit's export setting names, in the setting's order. A name the unit lacks is an error."""
    out = []
    for n in names:
        if n not in m["constants"]:
            raise GenError("%s: export constants name %s, which the unit does not define" % (m["unit"], n))
        out.append((n, m["constants"][n]))
    return out


def _items(group):
    """The (name, constant) and (name, register) lists of the units of one block. A name that two units both
    define is an error: the consumer would get two definitions of one name."""
    consts, regs, seen = [], [], {}
    for m, names in group:
        items = [(n, c, "const") for n, c in _named_constants(m, names)] + [(n, r, "reg") for n, r in m["registers"].items()]
        for n, v, kind in items:
            if n.upper() in seen:
                raise GenError("rust-regs: %s is defined by both %s and %s" % (n.upper(), seen[n.upper()], m["unit"]))
            seen[n.upper()] = m["unit"]
            (consts if kind == "const" else regs).append((n, v, m))
    return consts, regs


def _field(u, fn, f):
    text = "%s: %d..%d" % (fn.upper(), f["bits"][1], f["bits"][0])
    vals = enum_values(u, f)
    if vals:
        big = [lab for lab, v in vals.items() if v["value"] > 255]
        if big:     # the consumer's Value enum is one byte
            raise GenError("%s: field %s value %s is above 255" % (u["unit"], fn, big[0]))
        text += " { %s }" % ", ".join("%s = %d" % (lab.upper(), v["value"]) for lab, v in vals.items())
    return text


def _register(u, n, r, base, ind):
    """`NAME OFFSET width N`, then reset and the masks when the map has them, the array bounds and the fields."""
    off = r["offset"] - base
    parts = ["%s 0x%04x width %d" % (n.upper(), off, r["width"])]
    if isinstance(r["reset"], int):
        parts.append("reset 0x%x" % r["reset"])
    parts += ["%s 0x%x" % (k, r[k]) for k in MASKS if r.get(k)]
    if r["count"] > 1:
        parts.append("count %d stride 0x%x end 0x%x" % (r["count"], r["stride"], off + r["count"] * r["stride"]))
    if not r["fields"]:
        return [ind + " ".join(parts) + ";"]
    fl = [_field(u, fn, f) for fn, f in r["fields"].items()]
    line = "%s%s { %s };" % (ind, " ".join(parts), ", ".join(fl))
    if len(line) <= WRAP:
        return [line]
    return ["%s%s {" % (ind, " ".join(parts))] + ["%s    %s," % (ind, f) for f in fl] + [ind + "};"]


def _block(group, base, ind):
    consts, regs = _items(group)
    out = ["%sconst %s = 0x%x;" % (ind, n.upper(), c["value"]) for n, c, _m in consts]
    for n, r, m in regs:
        out += _register(m, n, r, base, ind)
    return out


def block_name(unit, fname):
    """The `unit` block name for a unit in a shared file: its name without the file name as a prefix."""
    return unit[len(fname) + 1:] if unit.startswith(fname + "_") else unit


def gen_rust_regs(fname, entries, source, commit):
    """One `regs!` invocation for the units of one file, `entries` being (unit name, base, model, constant names).
    Units on one base are written flat under a `base` line. Units on several bases get a `unit NAME base N` block
    each, so the consumer can tell the blocks apart. Grades and prose stay in the register map."""
    out = [export_banner(source, commit, "//"), "regs! {"]
    bases = {e[1] for e in entries}
    if len(bases) == 1:
        out.append("    base 0x%x;" % bases.pop())
        out += _block([(m, c) for _n, _b, m, c in entries], entries[0][1], "    ")
    else:
        names = {}
        for uname, base, m, c in entries:
            bn = block_name(uname, fname)
            if bn in names:
                raise GenError("rust-regs: units %s and %s both become the block %s" % (names[bn], uname, bn))
            names[bn] = uname
            out.append("    unit %s base 0x%x {" % (bn, base))
            out += _block([(m, c)], base, "        ")
            out.append("    }")
    out.append("}")
    return "\n".join(out) + "\n"


def gen_c_regfields(m, base, project, commit):
    blk = block_of(m)
    guard = "%s_REGFIELDS_H" % m["prefix"]
    out = [export_banner(project, commit, "/*", " */"),
           "/* %s */" % one_line(m.get("title") or m["unit"]),
           "/* Needs REG8, REG16, REG32, REG64 (name, offset) and FIELD (register, field, shift, length) defined by the",
           " * includer. Offsets are relative to %s_BASE. A comment gives each grade. */" % blk,
           "#ifndef %s\n#define %s\n" % (guard, guard),
           "#define %s_BASE 0x%x" % (blk, base)]
    for n, r in m["registers"].items():
        name = n.upper()
        out.append("")
        out.append("/* %s */" % r["grade"])
        out.append("%s(%s, 0x%x)" % (WIDE[r["width"]], name, r["offset"] - base))
        if r["count"] > 1:
            out.append("#define %s_COUNT %d" % (name, r["count"]))
            out.append("#define %s_STRIDE 0x%x" % (name, r["stride"]))
        for fn, f in r["fields"].items():
            hi, lo = f["bits"]
            out.append("FIELD(%s, %s, %d, %d)" % (name, fn.upper(), lo, hi - lo + 1))
    out.append("\n#endif /* %s */" % guard)
    return "\n".join(out) + "\n"


def render_export(repo, models, commit):
    """Return ({relative path: text}, [errors]) for the export profiles the settings ask for.
    `models` maps a unit name to the model the committed profile renders."""
    cfg = repo.settings.get("gen", {}).get("export", {})
    profiles, units = cfg.get("profiles", []), cfg.get("units", {})
    files, errors = {}, []
    if not profiles:
        if units:
            errors.append("gen.export.units is set but gen.export.profiles is empty")
        return files, errors
    lay = repo.layout
    rust = {}       # rust-regs file name -> [(unit name, base, model, constant names)]
    for name in sorted(units):
        if name not in models:
            errors.append("gen.export.units.%s: not a unit" % name)
            continue
        try:
            base = unit_base(models[name], units[name])
            if RUST_DIR in profiles:
                rust.setdefault(rust_file(units, name), []).append((name, base, models[name], units[name].get("constants", ())))
            if C_DIR in profiles:
                files["%s/%s/%s.h" % (lay.gen_root(), C_DIR, name)] = gen_c_regfields(models[name], base, repo.project, commit)
        except GenError as e:
            errors.append(str(e))
    for fname, entries in sorted(rust.items()):
        try:
            files["%s/%s/%s.rs" % (lay.gen_root(), RUST_DIR, fname)] = gen_rust_regs(
                fname, entries, cfg.get("source") or repo.project, commit)
        except GenError as e:
            errors.append(str(e))
    return files, errors


def rust_file(units, name):
    """The rust-regs file name a unit's registers are written to."""
    return units[name].get("rust_file") or name


def export_dirs(repo):
    root = repo.layout.gen_root()
    return ["%s/%s" % (root, d) for d in (RUST_DIR, C_DIR)]
